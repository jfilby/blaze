/** The Nim implementation of the runtime ABI, generated from abi.ts. */
export function generateRuntimeAdapterSource(): string {
  return `## Generated by the blaze compiler. Do not edit.
## The Nim host runtime adapter: the blaze runtime ABI on Nim's allocator.

type
  BlazeHeader = object
    magic: uint64
    base: pointer
    length: uint64
    alignment: uint64
    refs: uint64
    reserved: uint64

const
  BlazeMagic = 0x424C415A45525400'u64
  BlazeFreed = 0'u64
  BlazeHeaderSize = 48'u64
  BlazeDefaultAlignment = 16'u64
  BlazeMaxAllocation = 1'u64 shl 40

proc alignUp(value, alignment: uint64): uint64 =
  (value + alignment - 1) and not (alignment - 1)

proc headerOf(pointer: pointer): ptr BlazeHeader =
  cast[ptr BlazeHeader](cast[uint](pointer) - BlazeHeaderSize)

proc check(pointer: pointer, who: string): ptr BlazeHeader =
  if pointer == nil:
    raise newException(ValueError, who & ": null pointer")
  result = headerOf(pointer)
  if result[].magic != BlazeMagic:
    raise newException(ValueError, who & ": not a live blaze pointer")
  if result[].alignment == 0 or (result[].alignment and (result[].alignment - 1)) != 0:
    raise newException(ValueError, who & ": corrupt blaze header")

proc blaze_rt_initialize*() {.exportc, cdecl.} =
  discard

proc blaze_rt_finalize*() {.exportc, cdecl.} =
  discard

proc blaze_rt_allocate*(bytes: csize_t): pointer {.exportc, cdecl.} =
  let total = bytes.uint64 + BlazeHeaderSize
  if total > BlazeMaxAllocation:
    raise newException(ValueError, "blaze_rt_allocate: request too large")
  let base = allocShared0(int(total))
  if base == nil:
    raise newException(OutOfMemDefect, "blaze_rt_allocate: out of memory")
  var header = BlazeHeader(magic: BlazeMagic, base: base, length: bytes.uint64,
                           alignment: BlazeDefaultAlignment, refs: 1)
  cast[ptr BlazeHeader](base)[] = header
  result = cast[pointer](cast[uint](base) + BlazeHeaderSize)

proc blaze_rt_object_new*(bytes, alignment: csize_t): pointer {.exportc, cdecl.} =
  let align = if alignment == 0: BlazeDefaultAlignment else: alignment.uint64
  if (align and (align - 1)) != 0:
    raise newException(ValueError, "blaze_rt_object_new: alignment must be a power of two")
  let total = alignUp(bytes.uint64, align) + BlazeHeaderSize
  if total > BlazeMaxAllocation:
    raise newException(ValueError, "blaze_rt_object_new: request too large")
  let base = allocShared0(int(total))
  if base == nil:
    raise newException(OutOfMemDefect, "blaze_rt_object_new: out of memory")
  var header = BlazeHeader(magic: BlazeMagic, base: base, length: bytes.uint64,
                           alignment: align, refs: 1)
  cast[ptr BlazeHeader](base)[] = header
  result = cast[pointer](alignUp(cast[uint](base) + BlazeHeaderSize, align))

proc blaze_rt_reallocate*(pointer: pointer, bytes: csize_t): pointer {.exportc, cdecl.} =
  if pointer == nil:
    return blaze_rt_allocate(bytes)
  let header = check(pointer, "blaze_rt_reallocate")
  let total = header[].length + bytes.uint64 + BlazeHeaderSize
  if total > BlazeMaxAllocation:
    raise newException(ValueError, "blaze_rt_reallocate: request too large")
  let grown = reallocShared(header[].base, int(total))
  if grown == nil:
    raise newException(OutOfMemDefect, "blaze_rt_reallocate: out of memory")
  var updated = header[]
  updated.base = grown
  updated.length = bytes.uint64
  cast[ptr BlazeHeader](grown)[] = updated
  result = cast[pointer](alignUp(cast[uint](grown) + BlazeHeaderSize, updated.alignment))

proc blaze_rt_retain*(pointer: pointer): pointer {.exportc, cdecl.} =
  if pointer == nil:
    return nil
  inc check(pointer, "blaze_rt_retain")[].refs
  pointer

proc blaze_rt_release*(pointer: pointer) {.exportc, cdecl.} =
  if pointer == nil:
    return
  let header = check(pointer, "blaze_rt_release")
  if header[].refs > 1:
    dec header[].refs
    return
  let base = header[].base
  header[].magic = BlazeFreed
  deallocShared(base)

proc blaze_rt_string_new*(bytes: pointer, length: csize_t): cstring {.exportc, cdecl.} =
  let storage = blaze_rt_allocate(length.csize_t + 1)
  if length > 0:
    copyMem(storage, bytes, int(length))
  cast[ptr UncheckedArray[char]](storage)[int(length)] = '\\0'
  cast[cstring](storage)

proc blaze_rt_string_length*(text: cstring): csize_t {.exportc, cdecl.} =
  if text == nil:
    return 0
  check(cast[pointer](text), "blaze_rt_string_length")[].length - 1

proc blaze_rt_string_clone*(text: cstring): cstring {.exportc, cdecl.} =
  blaze_rt_string_new(cast[pointer](text), blaze_rt_string_length(text))

proc blaze_rt_array_new*(count, elementSize: csize_t): pointer {.exportc, cdecl.} =
  blaze_rt_allocate(count * elementSize)

proc blaze_rt_array_resize*(pointer: pointer, count, elementSize: csize_t): pointer {.exportc, cdecl.} =
  blaze_rt_reallocate(pointer, count * elementSize)

proc blaze_rt_object_size*(pointer: pointer): csize_t {.exportc, cdecl.} =
  if pointer == nil:
    return 0
  check(pointer, "blaze_rt_object_size")[].length

proc blaze_rt_last_error*(): cstring {.exportc, cdecl.} =
  ""

proc blaze_rt_raise*(message: cstring) {.exportc, cdecl, noreturn.} =
  raise newException(ValueError, if message == nil: "" else: $message)
`;
}

