/**
 * The blaze SQLite library.
 *
 * A SQLite program links a library beside the runtime it runs on: the
 * vendored amalgamation of SQLite and the adapter that answers the entry
 * points of the ABI. The two are compiled as one program and bundled into one
 * relocatable object, `blaze_sqlite.o`, which the program links beside its
 * runtime object.
 *
 * The amalgamation is vendored, not linked from the system, in the way facil.io
 * is vendored at `deps/facil.io`: it is public domain, and it is the whole
 * library as one translation unit, which is what makes it one file to compile.
 */

import { createHash, existsSync, readFileSync, writeFile, dirname, resolve, fileURLToPath } from "../core/platform.ts";
import { CompilerError } from "../core/errors.ts";
import { run } from "../core/process.ts";
import { cTargetOptions, optimizationOptions } from "../core/target.ts";
import type { BuildMode, TargetSpec } from "../core/types.ts";
import { SQLITE_ABI, SQLITE_NAME, sqliteHeaderSource } from "./sqlite.ts";

/** The repository root, used to locate the vendored SQLite source. */
const compilerDir = dirname(fileURLToPath(import.meta.url));
/** .../src/compiler/runtime -> repository root. */
const repoRoot = resolve(compilerDir, "../../..");

/** The vendored SQLite amalgamation, pinned to `SQLITE_VERSION`. */
export function vendoredSqliteDir(): string {
  return resolve(repoRoot, "deps/sqlite3");
}

/**
 * The flags the amalgamation is compiled with, which are what make it a
 * library rather than a program:
 *
 *   SQLITE_THREADSAFE=1         the serialized mode: a connection may be used
 *                                from another thread, but not while another
 *                                thread is using it
 *   SQLITE_OMIT_LOAD_EXTENSION  a program that loads an extension loads code
 *   SQLITE_DQS=0                the double-quoted string literals are off,
 *                                because SQLite accepts them as identifiers and
 *                                a program that writes one is a program with a
 *                                name nobody can be sure of
 *   SQLITE_DEFAULT_MEMSTATUS=0  the memory statistics are off: they are a
 *                                global the library would otherwise write on
 *                                every allocation
 *   SQLITE_OMIT_DEPRECATED      the interfaces SQLite deprecated are gone
 */
export const SQLITE_COMPILE_FLAGS: readonly string[] = [
  "-DSQLITE_THREADSAFE=1",
  "-DSQLITE_OMIT_LOAD_EXTENSION",
  "-DSQLITE_DQS=0",
  "-DSQLITE_DEFAULT_MEMSTATUS=0",
  "-DSQLITE_OMIT_DEPRECATED",
];

/**
 * The C that answers the entry points of the SQLite ABI.
 *
 * Every entry point of the table in `runtime/sqlite.ts` is implemented here, and
 * the build refuses to write an adapter that does not implement exactly the
 * table: a symbol of the table with no body, or a body with no symbol of the
 * table, is a boundary whose two sides have drifted apart.
 */
export function sqliteAdapterSource(): string {
  return `/* Generated by the blaze compiler. Do not edit.
 *
 * The blaze SQLite adapter: it answers the entry points of the blaze SQLite
 * ABI over the SQLite C library. SQLite's own types never appear in the ABI —
 * a handle is a number, and the adapter holds the pointer behind it, so a
 * program that prints a handle prints a number and not the bytes of a struct
 * it points at.
 */

#include <stdlib.h>
#include <string.h>

#include "sqlite3.h"
#include "blaze_rt.h"

/* -------------------------------------------------------------------------- */
/* The handles the adapter hands out.                                          */
/* -------------------------------------------------------------------------- */

/* What a handle holds: a connection, or a statement of one.

   A statement belongs to the connection that compiled it, and closing the
   connection finalizes the statements it holds: a statement that is not
   finalized is a leak, and a program that forgot one has no way to know. */
typedef struct blaze_sqlite_handle {
  int statement;                     /* 1 for a statement, 0 for a connection */
  size_t index;                      /* the slot this handle is held in */
  sqlite3* db;                       /* the connection, for both */
  sqlite3_stmt* stmt;                /* the statement, for a statement */
  struct blaze_sqlite_handle* owner; /* the connection a statement belongs to */
  struct blaze_sqlite_handle* next;  /* the next statement of the connection */
} blaze_sqlite_handle;

/* The handles the program holds.

   A handle is a number and not a pointer: it is the slot the handle is held
   in, and the adapter holds the pointer. A number the program holds is
   rendered as a number, which is what a handle has to be — the runtime renders
   a value it does not hold and that is above 4096 as if it were a string
   pointer, so a handle that was a pointer would be printed as the bytes of a
   struct. The slots are not reused, so the number a handle is does not depend
   on what the program did before it, and the source of the program and the
   program the compiler built print the same handle. */
static blaze_sqlite_handle** blaze_sqlite_handles = NULL;
static size_t blaze_sqlite_handle_count = 0;
static size_t blaze_sqlite_handle_capacity = 0;

/* The handle the program may hold: the slot it is held in. */
static double blaze_sqlite_handle_box(blaze_sqlite_handle* handle) {
  return (double)handle->index;
}

/* What a handle holds, or null when the number is not a handle at all. */
static blaze_sqlite_handle* blaze_sqlite_handle_get(double handle) {
  if (!(handle >= 0.0)) return NULL;
  double index = handle;
  if (index >= (double)blaze_sqlite_handle_count) return NULL;
  return blaze_sqlite_handles[(size_t)index];
}

/* A slot for a handle, made new: a slot is never reused, so a handle is a
   number the program can count on. */
static blaze_sqlite_handle* blaze_sqlite_handle_alloc(int statement, sqlite3* db, sqlite3_stmt* stmt) {
  blaze_sqlite_handle* handle = (blaze_sqlite_handle*)malloc(sizeof(blaze_sqlite_handle));
  if (handle == NULL) {
    blaze_rt_raise("out of memory");
    return NULL;
  }
  if (blaze_sqlite_handle_count == blaze_sqlite_handle_capacity) {
    size_t capacity = blaze_sqlite_handle_capacity ? blaze_sqlite_handle_capacity * 2 : 64;
    blaze_sqlite_handle** grown =
        (blaze_sqlite_handle**)realloc(blaze_sqlite_handles, capacity * sizeof(blaze_sqlite_handle*));
    if (grown == NULL) {
      blaze_rt_raise("out of memory");
      return NULL;
    }
    blaze_sqlite_handles = grown;
    blaze_sqlite_handle_capacity = capacity;
  }
  handle->index = blaze_sqlite_handle_count;
  handle->statement = statement;
  handle->db = db;
  handle->stmt = stmt;
  handle->owner = NULL;
  handle->next = NULL;
  blaze_sqlite_handles[blaze_sqlite_handle_count] = handle;
  blaze_sqlite_handle_count += 1;
  return handle;
}

/* A handle the program may not hold any more: the slot is free again. */
static void blaze_sqlite_handle_release(blaze_sqlite_handle* handle) {
  blaze_sqlite_handles[handle->index] = NULL;
  handle->next = NULL;
  handle->owner = NULL;
}

/* The connection a handle is, or null when the handle is not a connection. */
static blaze_sqlite_handle* blaze_sqlite_connection(double handle) {
  blaze_sqlite_handle* found = blaze_sqlite_handle_get(handle);
  if (found == NULL || found->statement) return NULL;
  return found;
}

/* The statement a handle is, or null when the handle is not a statement. */
static blaze_sqlite_handle* blaze_sqlite_statement(double handle) {
  blaze_sqlite_handle* found = blaze_sqlite_handle_get(handle);
  if (found == NULL || !found->statement) return NULL;
  return found;
}

/* -------------------------------------------------------------------------- */
/* The entry points of the ABI.                                                */
/* -------------------------------------------------------------------------- */

double blaze_sqlite_open(const char* path) {
  sqlite3* db = NULL;
  int code = sqlite3_open(path, &db);
  if (code != SQLITE_OK) {
    const char* message = db != NULL ? sqlite3_errmsg(db) : "the database could not be opened";
    blaze_rt_raise(message);
    if (db != NULL) sqlite3_close(db);
    return 0.0;
  }
  blaze_sqlite_handle* handle = blaze_sqlite_handle_alloc(0, db, NULL);
  return blaze_sqlite_handle_box(handle);
}

void blaze_sqlite_close(double db) {
  blaze_sqlite_handle* handle = blaze_sqlite_connection(db);
  if (handle == NULL) return;
  /* The statements the connection holds are finalized with it. */
  blaze_sqlite_handle* statement = handle->next;
  while (statement != NULL) {
    blaze_sqlite_handle* following = statement->next;
    if (statement->stmt != NULL) sqlite3_finalize(statement->stmt);
    statement->stmt = NULL;
    blaze_sqlite_handle_release(statement);
    statement = following;
  }
  handle->next = NULL;
  if (handle->db != NULL) {
    sqlite3_close(handle->db);
    handle->db = NULL;
  }
  blaze_sqlite_handle_release(handle);
}

double blaze_sqlite_exec(double db, const char* sql) {
  blaze_sqlite_handle* handle = blaze_sqlite_connection(db);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a database");
    return 0.0;
  }
  int code = sqlite3_exec(handle->db, sql, NULL, NULL, NULL);
  return code == SQLITE_OK ? 1.0 : 0.0;
}

double blaze_sqlite_prepare(double db, const char* sql) {
  blaze_sqlite_handle* handle = blaze_sqlite_connection(db);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a database");
    return 0.0;
  }
  sqlite3_stmt* stmt = NULL;
  int code = sqlite3_prepare_v2(handle->db, sql, -1, &stmt, NULL);
  if (code != SQLITE_OK) {
    blaze_rt_raise(sqlite3_errmsg(handle->db));
    return 0.0;
  }
  if (stmt == NULL) {
    blaze_rt_raise("the statement is empty");
    return 0.0;
  }
  blaze_sqlite_handle* statement = blaze_sqlite_handle_alloc(1, handle->db, stmt);
  statement->owner = handle;
  statement->next = handle->next;
  handle->next = statement;
  return blaze_sqlite_handle_box(statement);
}

void blaze_sqlite_bind_text(double stmt, double index, const char* value) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return;
  }
  int code = sqlite3_bind_text(handle->stmt, (int)index, value, -1, SQLITE_TRANSIENT);
  if (code != SQLITE_OK) blaze_rt_raise(sqlite3_errmsg(handle->db));
}

void blaze_sqlite_bind_number(double stmt, double index, double value) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return;
  }
  int code = sqlite3_bind_double(handle->stmt, (int)index, value);
  if (code != SQLITE_OK) blaze_rt_raise(sqlite3_errmsg(handle->db));
}

void blaze_sqlite_bind_null(double stmt, double index) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return;
  }
  int code = sqlite3_bind_null(handle->stmt, (int)index);
  if (code != SQLITE_OK) blaze_rt_raise(sqlite3_errmsg(handle->db));
}

double blaze_sqlite_step(double stmt) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return 0.0;
  }
  int code = sqlite3_step(handle->stmt);
  if (code == SQLITE_ROW) return 1.0;
  if (code == SQLITE_DONE) return 0.0;
  blaze_rt_raise(sqlite3_errmsg(handle->db));
  return 0.0;
}

double blaze_sqlite_column_count(double stmt) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return 0.0;
  }
  return (double)sqlite3_column_count(handle->stmt);
}

double blaze_sqlite_column_type(double stmt, double index) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return 0.0;
  }
  /* The kind is the API's own numbering: 0 null, 1 integer, 2 float, 3 text,
     4 blob. SQLite counts a null as five, because its four kinds are the ones
     a value can be and a null is the absence of all of them; the API counts
     it as none of them, which is what a program asks about. */
  int kind = sqlite3_column_type(handle->stmt, (int)index);
  if (kind == SQLITE_NULL) return 0.0;
  return (double)kind;
}

double blaze_sqlite_column_number(double stmt, double index) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return 0.0;
  }
  return sqlite3_column_double(handle->stmt, (int)index);
}

const char* blaze_sqlite_column_text(double stmt, double index) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a statement");
    return blaze_rt_string_new(NULL, 0);
  }
  /* The text is read before its length is measured: SQLite converts the value
     to text when it is read, and the length is the length of the text it
     converted. */
  const unsigned char* text = sqlite3_column_text(handle->stmt, (int)index);
  if (text == NULL) return blaze_rt_string_new(NULL, 0);
  int bytes = sqlite3_column_bytes(handle->stmt, (int)index);
  /* The runtime's text is NUL terminated, so a value with a NUL in it is
     refused rather than cut. */
  if ((int)strlen((const char*)text) != bytes) {
    blaze_rt_raise("a text column holds a NUL, which the runtime's text cannot carry");
  }
  return blaze_rt_string_new(text, (size_t)bytes);
}

void blaze_sqlite_finalize(double stmt) {
  blaze_sqlite_handle* handle = blaze_sqlite_statement(stmt);
  if (handle == NULL) return;
  /* The statement is taken off the connection that holds it, so that closing
     the connection does not finalize it a second time. */
  blaze_sqlite_handle* connection = handle->owner;
  if (connection != NULL) {
    blaze_sqlite_handle** link = &connection->next;
    while (*link != NULL) {
      if (*link == handle) {
        *link = handle->next;
        break;
      }
      link = &(*link)->next;
    }
  }
  if (handle->stmt != NULL) {
    sqlite3_finalize(handle->stmt);
    handle->stmt = NULL;
  }
  blaze_sqlite_handle_release(handle);
}

double blaze_sqlite_changes(double db) {
  blaze_sqlite_handle* handle = blaze_sqlite_connection(db);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a database");
    return 0.0;
  }
  return (double)sqlite3_changes(handle->db);
}

double blaze_sqlite_last_insert_rowid(double db) {
  blaze_sqlite_handle* handle = blaze_sqlite_connection(db);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a database");
    return 0.0;
  }
  return (double)sqlite3_last_insert_rowid(handle->db);
}

const char* blaze_sqlite_error(double db) {
  blaze_sqlite_handle* handle = blaze_sqlite_connection(db);
  if (handle == NULL) {
    blaze_rt_raise("the handle is not a database");
    return blaze_rt_string_new(NULL, 0);
  }
  const char* message = sqlite3_errmsg(handle->db);
  if (message == NULL) return blaze_rt_string_new(NULL, 0);
  return blaze_rt_string_new((const unsigned char*)message, strlen(message));
}
`;
}

/**
 * The entry points the adapter implements, and the ones the table names.
 *
 * The two are compared before the adapter is written: a symbol of the table
 * with no body, or a body with no symbol of the table, is a boundary whose two
 * sides have drifted apart, and a program that linked it would fail at the
 * link with a message about a symbol nobody wrote.
 */
function adapterEntries(): readonly string[] {
  const source = sqliteAdapterSource();
  const declared = SQLITE_ABI.map((entry) => entry.symbol);
  const written = [...source.matchAll(/^(?:double|void|const char\*) (blaze_sqlite_[a-z_]+)\(/gm)].map((match) => match[1]);
  const missing = declared.filter((symbol) => !written.includes(symbol));
  const extra = written.filter((symbol) => !declared.includes(symbol));
  if (missing.length > 0 || extra.length > 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "the SQLite adapter and the SQLite ABI do not agree",
      detail: [
        ...(missing.length === 0 ? [] : [`the adapter does not implement: ${missing.join(", ")}`]),
        ...(extra.length === 0 ? [] : [`the adapter implements what the ABI does not name: ${extra.join(", ")}`]),
      ].join("\n"),
    });
  }
  return declared;
}

export interface SqliteLibrary {
  /** The header a program that uses SQLite includes. */
  headerPath: string;
  /** The object the program links beside the runtime. */
  objectPath: string;
}

/**
 * The name the compiled amalgamation is kept under, which says what it was
 * built from: the flags it was compiled with and the source it was compiled
 * from. An object built from another set of flags is another object, and one
 * built from another version of the amalgamation is another object too.
 */
function sqliteObjectKey(flags: readonly string[], amalgamation: string): string {
  const material = [...flags, readFileSync(amalgamation)].join("\n");
  return createHash("sha256").update(material).digest("hex").slice(0, 16);
}

/**
 * Writes the header, compiles the amalgamation and the adapter, and bundles
 * the two into one relocatable object the program links beside its runtime.
 */
export async function buildSqliteLibrary(
  workDirectory: string,
  mode: BuildMode = "debug",
  target: TargetSpec = { arch: "x86_64", os: "linux", abi: "sysv", cpu: "", features: [] },
): Promise<SqliteLibrary> {
  adapterEntries();
  const headerPath = `${workDirectory}/${SQLITE_NAME}.h`;
  await writeFile(headerPath, sqliteHeaderSource(), "utf8");
  const adapterPath = `${workDirectory}/${SQLITE_NAME}.c`;
  await writeFile(adapterPath, sqliteAdapterSource(), "utf8");

  const sqliteDir = vendoredSqliteDir();
  const amalgamation = `${sqliteDir}/sqlite3.c`;
  const adapterObject = `${workDirectory}/${SQLITE_NAME}_adapter.o`;
  const objectPath = `${workDirectory}/${SQLITE_NAME}.o`;

  // The library is compiled without link-time optimization: the program is
  // linked with it, and an object that carries the compiler's intermediate form
  // is rebuilt at that link — which for the amalgamation is a build of the whole
  // of SQLite again, at the end of every build.
  const flags = [
    "-std=gnu11",
    ...optimizationOptions(mode).filter((flag) => flag !== "-flto" && flag !== "-ffat-lto-objects"),
    ...cTargetOptions(target),
    ...SQLITE_COMPILE_FLAGS,
    "-ffunction-sections",
    "-fdata-sections",
    "-pthread",
  ];

  // The amalgamation is a whole library in one file, and compiling it takes a
  // minute. The object is kept in the work directory under a name that says
  // what it was built from, so a build that follows another one does not pay
  // for it again.
  const sqliteObject = `${workDirectory}/sqlite3-${sqliteObjectKey(flags, amalgamation)}.o`;
  if (!existsSync(sqliteObject)) {
    const compiled = run("gcc", [...flags, "-c", "-o", sqliteObject, amalgamation], { timeoutMs: 600_000 });
    if (compiled.spawnError !== undefined) {
      throw new CompilerError({
        category: "TargetError",
        stage: "compile",
        message: "the C compiler is not available",
        detail: compiled.spawnError,
      });
    }
    if (compiled.code !== 0) {
      throw new CompilerError({
        category: "LinkError",
        stage: "compile",
        message: "the SQLite amalgamation did not build",
        detail: `${amalgamation}\n${compiled.stderr.trim()}`,
      });
    }
  }

  // The adapter includes the runtime's header, which the runtime wrote into the
  // work directory before this was built, and the amalgamation's header, which
  // is vendored beside it.
  const adapter = run(
    "gcc",
    [...flags, `-I${workDirectory}`, `-I${sqliteDir}`, "-c", "-o", adapterObject, adapterPath],
    { timeoutMs: 300_000 },
  );
  if (adapter.spawnError !== undefined) {
    throw new CompilerError({
      category: "TargetError",
      stage: "compile",
      message: "the C compiler is not available",
      detail: adapter.spawnError,
    });
  }
  if (adapter.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "the SQLite adapter did not build",
      detail: `${adapterPath}\n${adapter.stderr.trim()}`,
    });
  }

  // The two are bundled into one relocatable object, exactly as the facil
  // runtime bundles itself. The runtime's own entry points stay undefined
  // here and are resolved when the program is linked beside the runtime.
  const bundled = run("ld", ["-r", "-o", objectPath, adapterObject, sqliteObject], { timeoutMs: 120_000 });
  if (bundled.spawnError !== undefined || bundled.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "link",
      message: "the SQLite library did not bundle",
      detail: bundled.stderr.trim() ?? bundled.spawnError ?? "",
    });
  }

  return { headerPath, objectPath };
}
