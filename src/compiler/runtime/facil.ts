/** Builds and compiles facil.io together with the adapter, bundled into one object. */
export async function buildFacilRuntime(
  workDirectory: string,
  mode: BuildMode = "debug",
  target: TargetSpec = { arch: "x86_64", os: "linux", abi: "sysv", cpu: "", features: [] },
  needs: HttpRuntimeNeeds = defaultHttpRuntimeNeeds(),
): Promise<FacilRuntime> {
  const headerPath = await writeHttpHeader(workDirectory);
  /* The driver also includes the core runtime header, so write it beside the
     HTTP one. */
  await writeRuntimeHeader(workDirectory);
  const adapterSource = `${workDirectory}/${HTTP_NAME}_adapter.c`;
  const adapterObject = `${workDirectory}/${HTTP_NAME}_adapter.o`;
  const bundledObject = `${workDirectory}/${HTTP_NAME}.o`;

  await writeFile(adapterSource, facilAdapterSource(), "utf8");

  const sourceDir = facilIoSourceDir();
  let sourceDirOk = false;
  try {
    sourceDirOk = (await stat(sourceDir)).isDirectory();
  } catch {
    sourceDirOk = false;
  }
  if (!sourceDirOk) {
    throw new CompilerError({
      category: "LinkError",
      stage: "link",
      message: "facil.io is not available",
      detail: `the facil.io HTTP runtime requires its vendored source at ${sourceDir}, pinned to ${FACIL_IO_VERSION}`,
    });
  }

  /* List facil.io's C translation units needed for an HTTP server.
     Excluded: cli (command-line parsing), legacy (broken legacy allocator) and
     redis (Redis client). The TLS backend is the one that is chosen rather
     than excluded: a program that speaks TLS gets the OpenSSL one, and a
     program that does not gets the missing one, which is the same API with
     nothing behind it. */
  const excluded = ["/cli/", "/legacy/", "/redis/"];
  const listed = run(
    "sh",
    ["-c", `find "${sourceDir}" -name "*.c" -type f | sort`],
    { timeoutMs: 30_000 },
  );
  if (listed.spawnError !== undefined || listed.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "could not enumerate facil.io sources",
      detail: `${listed.stderr.trim() ?? listed.spawnError ?? ""}`,
    });
  }
  const tlsBackend = needs.tls ? "/tls/fio_tls_openssl.c" : "/tls/fio_tls_missing.c";
  const facilSources = listed.stdout
    .trim()
    .split("\n")
    .filter((line) => line.length > 0 && !excluded.some((e) => line.includes(e)))
    .filter((line) => !line.includes("/tls/fio_tls_openssl.c") && !line.includes("/tls/fio_tls_missing.c"))
    .concat(`${sourceDir}${tlsBackend}`);
  if (facilSources.length === 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "no facil.io sources found",
      detail: sourceDir,
    });
  }

  /* facil.io spreads its public headers across subdirectories, so add every
     subdirectory as an include path (fio.h itself includes <http.h>,
     <fiobj.h>, etc., and http.c needs <http1_parser.h> one level deeper). */
  const includeDirs: string[] = [];
  const collect = async (dir: string): Promise<void> => {
    for await (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = `${dir}/${entry.name}`;
      if (entry.isDirectory()) {
        includeDirs.push(full);
        await collect(full);
      }
    }
  };
  includeDirs.push(sourceDir);
  await collect(sourceDir);
  const cFlags = [
    "-std=gnu11",
    "-D_GNU_SOURCE",
    "-D_POSIX_C_SOURCE=200809L",
    /* The TLS backend is the one the program needs: a program that speaks TLS
       gets OpenSSL, and a program that does not gets neither the backend nor
       the library, so it does not load a TLS library before it runs. */
    ...(needs.tls ? ["-DHAVE_OPENSSL", "-DFIO_TLS_FOUND"] : []),
    /* How many connections the event loop may hold at once. facil.io sizes
       the table of them by the limit the process was given for open files,
       which on a machine with a generous limit is 131072 entries: about thirty
       megabytes that the program pays for in a page fault before it answers
       its first request. The table is as long as the program needs it to be,
       and a program that says how many connections it wants is given room
       for them. */
    `-DFIO_MAX_SOCK_CAPACITY=${needs.maxConnections}`,
    /* How much memory facil.io keeps for itself between the things it
       allocates. The pool is mapped and unmapped before the program answers
       its first request, so a pool of eight megabytes is eight megabytes the
       program pays for and never fills. */
    `-DFIO_MEMORY_BLOCKS_PER_ALLOCATION=${FACIL_IO_MEMORY_BLOCKS}`,
    /* How long facil.io's event loop waits for an event before it looks at
       what it was asked to do. The loop is stopped from another thread, and
       the thread that waits for the event is not woken by the request: it
       notices it when the wait is over. So the tick is the shortest a program
       waits for its server to end, and it is paid on every run of a program
       that starts a server and closes it again. */
    `-DFIO_POLL_TICK=${FACIL_IO_POLL_TICK_MS}`,
    ...optimizationOptions(mode),
    ...cTargetOptions(target),
    "-ffunction-sections",
    "-fdata-sections",
    "-pthread",
    ...includeDirs.map((dir) => `-I${dir}`),
  ];

  /* Compile each facil.io translation unit into its own object. */
  const facilObjects: string[] = [];
  facilSources.forEach((source, index) => {
    const objectPath = `${workDirectory}/facil_${index}.o`;
    const compiled = run(
      "gcc",
      [...cFlags, "-c", "-o", objectPath, source],
      { timeoutMs: 300_000 },
    );
    if (compiled.spawnError !== undefined || compiled.code !== 0) {
      throw new CompilerError({
        category: "LinkError",
        stage: "compile",
        message: "facil.io did not compile",
        detail: `${source}\\n${compiled.stderr.trim() ?? compiled.spawnError ?? ""}`,
      });
    }
    facilObjects.push(objectPath);
  });

  /* Compile the adapter. The adapter is told whether the runtime it is built
     for speaks TLS, so that the entry point that starts a TLS server is not
     compiled into a runtime that has no TLS behind it. */
  const compiled = run(
    "gcc",
    [...cFlags, ...(needs.tls ? ["-DBLAZE_HTTP_TLS=1"] : []), "-c", "-o", adapterObject, adapterSource],
    { timeoutMs: 300_000 },
  );
  if (compiled.spawnError !== undefined || compiled.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "the HTTP adapter did not compile",
      detail: `${adapterSource}\\n${compiled.stderr.trim() ?? compiled.spawnError ?? ""}`,
    });
  }

  /* The core compiler runtime is needed beside facil.io: the driver links it
     for allocate, print, and the rest of the blaze_rt ABI. */
  const rtSource = `${workDirectory}/${RUNTIME_NAME}.c`;
  const rtObject = `${workDirectory}/${RUNTIME_NAME}.o`;
  await writeFile(rtSource, runtimeSourceSource(mode), "utf8");
  const rtCompiled = run(
    "gcc",
    [...cFlags, "-c", "-o", rtObject, rtSource],
    { timeoutMs: 120_000 },
  );
  if (rtCompiled.spawnError !== undefined || rtCompiled.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "the compiler runtime did not build",
      detail: `${rtSource}\\n${rtCompiled.stderr.trim() ?? rtCompiled.spawnError ?? ""}`,
    });
  }

  /* Bundle facil.io, the adapter and the core runtime into one relocatable object the driver links.
     OpenSSL symbols stay undefined here and are resolved when the final program is linked with -lssl -lcrypto. */
  const linked = run(
    "ld",
    ["-r", "-o", bundledObject, adapterObject, rtObject, ...facilObjects],
    { timeoutMs: 120_000 },
  );
  if (linked.spawnError !== undefined || linked.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "link",
      message: "the HTTP runtime did not bundle",
      detail: `${linked.stderr.trim() ?? linked.spawnError ?? ""}`,
    });
  }

  return { headerPath, objectPath: bundledObject };
}
