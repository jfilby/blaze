/**
 * The facil.io HTTP runtime.
 *
 * A build with `--runtime facil` links the facil.io HTTP server behind a thin
 * C adapter. The adapter implements the HTTP ABI (`runtime/http.ts`) on top of
 * facil.io's networking, HTTP parsing and event loop, so generated Blaze code
 * never calls facil.io directly. `--runtime none` never touches facil.io.
 *
 * facil.io is a vendored dependency, pinned below. Its source lives at
 * `deps/facil.io/` (relative to the repository root) and is compiled once per
 * work directory, then bundled together with the adapter into a single
 * relocatable object that the program driver links.
 */

import { readdir, stat, writeFile } from "node:fs/promises";
import { CompilerError } from "../core/errors.ts";
import { run } from "../core/process.ts";
import { httpHeaderSource, HTTP_NAME } from "./http.ts";
import { cTargetOptions, optimizationOptions } from "../core/target.ts";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import type { BuildMode, TargetSpec } from "../core/types.ts";

export interface FacilRuntime {
  headerPath: string;
  objectPath: string;
}

/** The facil.io version Blaze is pinned to: the latest code from git master. */
export const FACIL_IO_VERSION = "facil.io@git-master";

/** The repository root, used to locate the vendored facil.io source. */
const compilerDir = dirname(fileURLToPath(import.meta.url));
/** .../src/compiler/runtime -> repository root. */
const repoRoot = resolve(compilerDir, "../../..");

/** The vendored facil.io source, pinned to `FACIL_IO_VERSION`. */
export function vendoredFacilIoDir(): string {
  return resolve(repoRoot, "deps/facil.io");
}

/** Where facil.io's C sources and public headers live inside the vendored copy. */
export function facilIoSourceDir(): string {
  return resolve(vendoredFacilIoDir(), "lib/facil");
}

/** The generated HTTP header a program that uses the HTTP runtime includes. */
export async function writeHttpHeader(workDirectory: string): Promise<string> {
  const headerPath = `${workDirectory}/${HTTP_NAME}.h`;
  await writeFile(headerPath, httpHeaderSource(), "utf8");
  return headerPath;
}

/** The C adapter source, written into the work directory and compiled. */
export function facilAdapterSource(): string {
  return `/* Generated by the blaze compiler. Do not edit.
 *
 * The facil.io HTTP adapter: implements the blaze HTTP ABI on top of
 * facil.io. A route handler registered by a Blaze program is invoked here
 * with a borrowed request and a borrowed response, both of which are valid for
 * the lifetime of the request the handler is serving.
 */

#include <stddef.h>
#include <stdint.h>
#include <string.h>

#include "${HTTP_NAME}.h"

/* facil.io, pinned to FACIL_IO_VERSION. facil.io's own types never appear in
   the public blaze_http.h header: they are confined to this adapter. */
#include <fio.h>
#include <http.h>
#include <fiobj_hash.h>
#include <fiobj_str.h>

#define BLAZE_HTTP_MAX_ROUTES 16
#define BLAZE_HTTP_HEADER_BUF 2048

/* -------------------------------------------------------------------------- */
/* Internal handle representations (opaque in blaze_http.h).                  */
/* -------------------------------------------------------------------------- */

/* A server. facil.io identifies a listener by a uuid (intptr_t), so the
   server records its uuid and the routes registered against it. */
typedef struct blaze_http_server_s {
  intptr_t uuid;
  int bound;
  size_t route_count;
  char *methods[BLAZE_HTTP_MAX_ROUTES];
  char *paths[BLAZE_HTTP_MAX_ROUTES];
  void (*handlers[BLAZE_HTTP_MAX_ROUTES])(blaze_http_request *, blaze_http_response *);
} blaze_http_server_t;

/* A request, borrowed from facil.io for the duration of one callback. */
typedef struct blaze_http_request_s {
  http_s *h;                      /* the facil.io request/response handle */
  char *method_copy;              /* NUL-terminated copy of the method */
  char *path_copy;                /* NUL-terminated copy of the path */
  char header_buf[BLAZE_HTTP_HEADER_BUF]; /* scratch for one header value */
} blaze_http_request_t;

/* A response, built by the handler and sent by the adapter on completion. */
typedef struct blaze_http_response_s {
  http_s *h;                      /* the facil.io request/response handle */
  unsigned char *body_copy;       /* copied body bytes */
  size_t body_len;                /* body byte count */
} blaze_http_response_t;

/* -------------------------------------------------------------------------- */
/* The request accessors the HTTP ABI exposes.                                */
/* -------------------------------------------------------------------------- */

const char *blaze_http_req_method(blaze_http_request *request) {
  blaze_http_request_t *req = (blaze_http_request_t *)request;
  if (!req || !req->method_copy) return "";
  return req->method_copy;
}

const char *blaze_http_req_path(blaze_http_request *request) {
  blaze_http_request_t *req = (blaze_http_request_t *)request;
  if (!req || !req->path_copy) return "";
  return req->path_copy;
}

const char *blaze_http_req_header(blaze_http_request *request, const char *name) {
  blaze_http_request_t *req = (blaze_http_request_t *)request;
  if (!req || !req->h || !name) return "";
  FIOBJ key = fiobj_str_new(name, strlen(name));
  FIOBJ value = fiobj_hash_get(req->h->headers, key);
  fiobj_free(key);
  if (!value) return "";
  fio_str_info_s vs = fiobj_obj2cstr(value);
  if (vs.len >= BLAZE_HTTP_HEADER_BUF) vs.len = BLAZE_HTTP_HEADER_BUF - 1;
  memcpy(req->header_buf, vs.data, vs.len);
  req->header_buf[vs.len] = '\\0';
  return req->header_buf;
}

const char *blaze_http_req_body(blaze_http_request *request, size_t *length) {
  blaze_http_request_t *req = (blaze_http_request_t *)request;
  if (!req || !req->h || !length) {
    if (length) *length = 0;
    return "";
  }
  /* The body is borrowed: valid for the request's lifetime. Its length, not a
     terminator, is what a reader uses. */
  fio_str_info_s body = fiobj_obj2cstr(req->h->body);
  *length = body.len;
  return body.data;
}

/* -------------------------------------------------------------------------- */
/* The response builders the HTTP ABI exposes.                                */
/* -------------------------------------------------------------------------- */

void blaze_http_resp_status(blaze_http_response *response, uint16_t status) {
  blaze_http_response_t *resp = (blaze_http_response_t *)response;
  if (!resp || !resp->h) return;
  resp->h->status = status;
}

void blaze_http_resp_header(blaze_http_response *response, const char *name,
                            const char *value) {
  blaze_http_response_t *resp = (blaze_http_response_t *)response;
  if (!resp || !resp->h || !name) return;
  fio_str_info_s n = {0, strlen(name), (char *)name};
  fio_str_info_s v = {0, strlen(value), (char *)value};
  http_set_header2(resp->h, n, v);
}

void blaze_http_resp_body(blaze_http_response *response, const unsigned char *bytes,
                          size_t length) {
  blaze_http_response_t *resp = (blaze_http_response_t *)response;
  if (!resp || !resp->h) return;
  if (resp->body_copy) free(resp->body_copy);
  resp->body_copy = length ? (unsigned char *)malloc(length) : NULL;
  if (resp->body_copy && length) memcpy(resp->body_copy, bytes, length);
  resp->body_len = length;
}

void blaze_http_resp_complete(blaze_http_response *response) {
  blaze_http_response_t *resp = (blaze_http_response_t *)response;
  if (!resp || !resp->h) return;
  /* http_send_body sends the buffered status/headers and body, copying the
     body, then invalidates the handle. */
  http_send_body(resp->h, resp->body_copy, resp->body_len);
  resp->h = NULL;
}

/* -------------------------------------------------------------------------- */
/* The route handler the adapter invokes for every matched request.           */
/* -------------------------------------------------------------------------- */

static void blaze_http_on_request(http_s *h) {
  struct http_settings_s *settings = http_settings(h);
  blaze_http_server_t *server = (blaze_http_server_t *)settings->udata;
  if (!server) {
    http_send_error(h, 500);
    return;
  }

  blaze_http_request_t req;
  blaze_http_response_t resp;
  __builtin_memset(&req, 0, sizeof(req));
  __builtin_memset(&resp, 0, sizeof(resp));
  req.h = h;
  resp.h = h;

  /* NUL-terminated copies of method and path, owned by this request. */
  {
    fio_str_info_s m = fiobj_obj2cstr(h->method);
    req.method_copy = (char *)malloc(m.len + 1);
    if (req.method_copy) {
      memcpy(req.method_copy, m.data, m.len);
      req.method_copy[m.len] = '\\0';
    }
    fio_str_info_s p = fiobj_obj2cstr(h->path);
    req.path_copy = (char *)malloc(p.len + 1);
    if (req.path_copy) {
      memcpy(req.path_copy, p.data, p.len);
      req.path_copy[p.len] = '\\0';
    }
  }

  void (*handler)(blaze_http_request *, blaze_http_response *) = NULL;
  for (size_t index = 0; index < server->route_count; index += 1) {
    int method_match = server->methods[index][0] == '*' ||
        strcmp(server->methods[index], req.method_copy) == 0;
    int path_match = server->paths[index][0] == '*' ||
        strcmp(server->paths[index], req.path_copy) == 0;
    if (method_match && path_match) {
      handler = server->handlers[index];
      break;
    }
  }

  if (handler) {
    handler((blaze_http_request *)&req, (blaze_http_response *)&resp);
  } else {
    http_send_error(h, 404);
  }

  free(req.method_copy);
  free(req.path_copy);
  free(resp.body_copy);
}

/* -------------------------------------------------------------------------- */
/* The server: start, run and stop.                                           */
/* -------------------------------------------------------------------------- */

void *blaze_http_server_new(uint16_t port) {
  blaze_http_server_t *server = (blaze_http_server_t *)calloc(1, sizeof(*server));
  if (!server) return NULL;

  char port_str[8];
  __builtin_snprintf(port_str, sizeof(port_str), "%u", (unsigned)port);

  intptr_t uuid = http_listen(port_str, NULL, .on_request = blaze_http_on_request,
                              .udata = server);
  if (uuid == -1) {
    free(server);
    return NULL;
  }

  server->uuid = uuid;
  server->bound = 1;
  return server;
}

void blaze_http_server_run(void *server_raw) {
  blaze_http_server_t *server = (blaze_http_server_t *)server_raw;
  if (!server || !server->bound) return;
  /* facil.io runs the event loop on this thread until fio_stop is called. */
  fio_start(.threads = 1, .workers = 1);
}

void blaze_http_server_stop(void *server_raw) {
  blaze_http_server_t *server = (blaze_http_server_t *)server_raw;
  if (!server) return;
  fio_stop();
  for (size_t index = 0; index < server->route_count; index += 1) {
    free(server->methods[index]);
    free(server->paths[index]);
  }
  free(server);
}

/* -------------------------------------------------------------------------- */
/* Route registration.                                                        */
/* -------------------------------------------------------------------------- */

void blaze_http_route_register(void *server_raw, const char *method,
                               const char *path, void (*handler)(void *, void *)) {
  blaze_http_server_t *server = (blaze_http_server_t *)server_raw;
  if (!server || !server->bound || !method || !path) return;
  if (server->route_count >= BLAZE_HTTP_MAX_ROUTES) return;
  server->methods[server->route_count] = strdup(method);
  server->paths[server->route_count] = strdup(path);
  server->handlers[server->route_count] = handler;
  server->route_count += 1;
}
`
}

/** Builds and compiles facil.io together with the adapter, bundled into one object. */
export async function buildFacilRuntime(
  workDirectory: string,
  mode: BuildMode = "debug",
  target: TargetSpec = { arch: "x86_64", os: "linux", abi: "sysv", cpu: "", features: [] },
): Promise<FacilRuntime> {
  const headerPath = await writeHttpHeader(workDirectory);
  const adapterSource = `${workDirectory}/${HTTP_NAME}_adapter.c`;
  const adapterObject = `${workDirectory}/${HTTP_NAME}_adapter.o`;
  const bundledObject = `${workDirectory}/${HTTP_NAME}.o`;

  await writeFile(adapterSource, facilAdapterSource(), "utf8");

  const sourceDir = facilIoSourceDir();
  let sourceDirOk = false;
  try {
    sourceDirOk = (await stat(sourceDir)).isDirectory();
  } catch {
    sourceDirOk = false;
  }
  if (!sourceDirOk) {
    throw new CompilerError({
      category: "LinkError",
      stage: "link",
      message: "facil.io is not available",
      detail: `the facil.io HTTP runtime requires its vendored source at ${sourceDir}, pinned to ${FACIL_IO_VERSION}`,
    });
  }

  /* List facil.io's C translation units needed for an HTTP server.
     Excluded: cli (command-line parsing), legacy (broken legacy allocator),
     redis (Redis client), and the OpenSSL TLS backend (Blaze does not enable
     HAVE_OPENSSL; fio_tls_missing.c is kept as the TLS fallback). */
  const excluded = ["/cli/", "/legacy/", "/redis/", "/tls/fio_tls_openssl.c"];
  const listed = run(
    "sh",
    ["-c", `find "${sourceDir}" -name "*.c" -type f | sort`],
    { timeoutMs: 30_000 },
  );
  if (listed.spawnError !== undefined || listed.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "could not enumerate facil.io sources",
      detail: `${listed.stderr.trim() ?? listed.spawnError ?? ""}`,
    });
  }
  const facilSources = listed.stdout
    .trim()
    .split("\n")
    .filter((line) => line.length > 0 && !excluded.some((e) => line.includes(e)));
  if (facilSources.length === 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "no facil.io sources found",
      detail: sourceDir,
    });
  }

  /* facil.io spreads its public headers across subdirectories, so add every
     subdirectory as an include path (fio.h itself includes <http.h>,
     <fiobj.h>, etc.). */
  const includeDirs = [sourceDir];
  for await (const entry of await readdir(sourceDir, { withFileTypes: true })) {
    if (entry.isDirectory()) includeDirs.push(`${sourceDir}/${entry.name}`);
  }
  const cFlags = [
    "-std=c11",
    "-D_POSIX_C_SOURCE=200809L",
    ...optimizationOptions(mode),
    ...cTargetOptions(target),
    "-ffunction-sections",
    "-fdata-sections",
    ...includeDirs.map((dir) => `-I${dir}`),
  ];

  /* Compile each facil.io translation unit into its own object. */
  const facilObjects: string[] = [];
  facilSources.forEach((source, index) => {
    const objectPath = `${workDirectory}/facil_${index}.o`;
    const compiled = run(
      "gcc",
      [...cFlags, "-c", "-o", objectPath, source],
      { timeoutMs: 300_000 },
    );
    if (compiled.spawnError !== undefined || compiled.code !== 0) {
      throw new CompilerError({
        category: "LinkError",
        stage: "compile",
        message: "facil.io did not compile",
        detail: `${source}\\n${compiled.stderr.trim() ?? compiled.spawnError ?? ""}`,
      });
    }
    facilObjects.push(objectPath);
  });

  /* Compile the adapter. */
  const compiled = run(
    "gcc",
    [...cFlags, "-c", "-o", adapterObject, adapterSource],
    { timeoutMs: 300_000 },
  );
  if (compiled.spawnError !== undefined || compiled.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "compile",
      message: "the HTTP adapter did not compile",
      detail: `${adapterSource}\\n${compiled.stderr.trim() ?? compiled.spawnError ?? ""}`,
    });
  }

  /* Bundle facil.io and the adapter into one relocatable object the driver links. */
  const linked = run(
    "ld",
    ["-r", "-o", bundledObject, adapterObject, ...facilObjects],
    { timeoutMs: 120_000 },
  );
  if (linked.spawnError !== undefined || linked.code !== 0) {
    throw new CompilerError({
      category: "LinkError",
      stage: "link",
      message: "the HTTP runtime did not bundle",
      detail: `${linked.stderr.trim() ?? linked.spawnError ?? ""}`,
    });
  }

  return { headerPath, objectPath: bundledObject };
}
