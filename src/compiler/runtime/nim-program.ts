/**
 * The Nim program driver.
 *
 * A hosted build (`runtime: nim`) delivers a Nim program: this driver is that
 * program. It runs the same statements as the C driver (see
 * toolchain/driver.ts) and calls the same compiled functions through the
 * runtime ABI, so a build behaves the same whichever host it links.
 *
 * The host owns `main` and the delivered binary is its output, exactly as it
 * is for a function build (see runtime/nim.ts).
 */

