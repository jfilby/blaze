import { RUNTIME_ANCHOR, RUNTIME_NAME } from "./abi.ts";
import { generateRuntimeAdapterSource, nimType } from "./nim.ts";

/**
 * One double as the source language prints it: the shortest decimal that reads
 * back as the same value, written in full from 1e-6 up to 1e21 and in
 * exponential form outside that range. See toolchain/program.ts for the rule.
 */
const NUMBER_PRINTER = `
# The shortest decimal that reads back as this value, printed the way the
# source language prints a number.
proc programNumber(value: float64): string =
  if value == 0.0:
    return (if classify(value) == fcNegZero: "-0" else: "0")
  let negative = value < 0.0
  let magnitude = (if negative: -value else: value)
  var precision = 0
  var text = formatBiggestFloat(magnitude, ffScientific, 0)
  while precision < 17:
    text = formatBiggestFloat(magnitude, ffScientific, precision)
    if parseFloat(text) == magnitude: break
    precision += 1

  # text is d.ddde[+-]XX: the digits, and where the decimal point belongs.
  let marker = text.find('e')
  let digits = text[0 ..< marker].replace(".", "")
  let point = parseInt(text[marker + 1 .. ^1]) + 1

  var result = (if negative: "-" else: "")
  if point >= -5 and point <= 21:
    if point <= 0:
      result.add("0." & repeat("0", -point) & digits)
    elif point >= digits.len:
      result.add(digits & repeat("0", point - digits.len))
    else:
      result.add(digits[0 ..< point] & "." & digits[point .. ^1])
    return result
  result.add($digits[0])
  if digits.len > 1:
    result.add("." & digits[1 .. ^1])
  let exponent = point - 1
  result.add("e" & (if exponent < 0: "-" else: "+") & $abs(exponent))
  result
`;

const HOST_PRELUDE = `## Generated by the blaze compiler from a program. Do not edit.
import std/[strutils, math]
import ${RUNTIME_NAME}
${NUMBER_PRINTER}
proc programFail(message: string) =
  stderr.write("program: " & message & "\\n")
  quit(2)
`;

function hostError(message: string, detail?: string): CompilerError {
  return new CompilerError({ category: "LinkError", stage: "host", message, detail });
}

const NIM_ELEMENT_SIZES: Record<string, number> = {
  bool: 1,
  i8: 1,
  i16: 2,
  i32: 4,
  i64: 8,
  u8: 1,
  u16: 2,
  u32: 4,
  u64: 8,
  f32: 4,
  f64: 8,
  usize: 8,
  isize: 8,
};

function elementNim(type: TypeExpr): string {
  if (type.kind !== "primitive") throw hostError(`the driver cannot hold a ${typeToString(type)} element`);
  return nimType(type);
}

/** Nim holds a buffer as an unchecked array, so the driver can fill it. */
function bufferNimType(element: string): string {
  return `ptr UncheckedArray[${element}]`;
}

function elementSize(type: TypeExpr): number {
  const size = type.kind === "primitive" ? NIM_ELEMENT_SIZES[type.name] : undefined;
  if (size === undefined) throw hostError(`the driver cannot size a ${typeToString(type)} element`);
  return size;
}

function nimString(text: string): string {
  const escaped = text
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")
    .replace(/\r/g, "\\r");
  return `"${escaped}"`;
}

function literal(text: string, element: string): string {
  if (element === "bool") return text === "0" ? "false" : "true";
  if (element !== "f32" && element !== "f64") return text;
  if (/^[+-]?0[xX]/.test(text)) return `${BigInt(text).toString()}.0`;
  return /^[+-]?[0-9]+$/.test(text) ? `${text}.0` : text;
}

function isFloat(type: TypeExpr | null): boolean {
  return type !== null && type.kind === "primitive" && (type.name === "f32" || type.name === "f64");
}

/** The Nim driver of one program, written out statement by statement. */
class NimDriver {
  private readonly temporaries = new Map<Binding, string>();
  private readonly allocated = new Set<string>();
  private readonly program: ResolvedProgram;
  private emitted = 0;

  constructor(program: ResolvedProgram) {
    this.program = program;
  }

  emit(): string {
    const externs = this.program.functions.map((signature) => this.declaration(signature));
    const anchor = RUNTIME_ANCHOR.map((symbol) => `  cast[pointer](${symbol}),`).join("\n");
    return `${HOST_PRELUDE}
{.emit: """
${externs.join("\n")}
""".}

${this.program.functions.map((signature) => this.importc(signature)).join("\n\n")}

proc main() =
  # Every entry point is named here, so the linker keeps the ones a candidate
  # calls even when this program does not call them itself.
  let runtimeAbi = [
${anchor}
  ]
  discard runtimeAbi.len
  ${RUNTIME_NAME}_initialize()
${this.program.statements.map((statement) => this.statement(statement)).join("\n")}
${[...this.allocated].map((name) => `  ${RUNTIME_NAME}_release(cast[pointer](${name}))`).join("\n")}
  ${RUNTIME_NAME}_finalize()

main()
`;
  }

  /** The C prototype a candidate is linked against, emitted into the program. */
  private declaration(signature: FunctionSignature): string {
    const returns = parseType(signature.returns);
    if (returns.kind === "ptr" || returns.kind === "slice" || returns.kind === "array") {
      throw hostError(
        `a program cannot call ${signature.name}`,
        `${typeToString(returns)} is returned, and a program holds numbers`,
      );
    }
    const parameters = signature.params.map((param) => `${cDeclarationType(parseType(param.type))} ${param.name}`);
    return `extern ${cDeclarationType(returns)} ${signature.name}(${parameters.join(", ") || "void"});`;
  }

  private importc(signature: FunctionSignature): string {
    const parameters = signature.params.map((param) => {
      const type = parseType(param.type);
      return `${param.name}: ${type.kind === "primitive" ? elementNim(type) : `ptr ${elementNim(type.of)}`}`;
    });
    return `proc ${signature.name}(${parameters.join(", ")}): ${nimType(parseType(signature.returns))} {.importc: "${signature.name}", nodecl.}`;
  }

  private statement(statement: ResolvedStatement): string {
    this.emitted += 1;
    this.temporaries.clear();
    const hoisted = this.hoist(statement.value, statement.kind === "declare" ? statement.name : undefined);
    if (statement.kind === "print") {
      return [...hoisted, ...this.print(statement.value), "  stdout.write(\"\\n\")"].join("\n");
    }
    return [...hoisted, this.declarationOf(statement)].join("\n");
  }

  /** Names every buffer literal a value tree holds, and allocates it. */
  private hoist(value: ResolvedValue, declaredAs?: string): string[] {
    if (value.k === "buffer") {
      const binding = value.binding;
      if (this.temporaries.has(binding)) return [];
      const name = declaredAs ?? `buffer_${this.emitted}_${this.temporaries.size}`;
      this.temporaries.set(binding, name);
      this.allocated.add(name);
      const element = binding.element ?? "f64";
      return [
        `  var ${name} = cast[${bufferNimType(elementNim(parseType(element)))}](${RUNTIME_NAME}_allocate(${binding.length} * ${elementSize(parseType(element))}))`,
        `  if ${name} == nil: programFail("out of memory")`,
        ...binding.values.map((text, index) => `  ${name}[${index}] = ${literal(text, element)}`),
      ];
    }
    if (value.k === "call") return value.call.args.flatMap((argument) => this.hoist(argument));
    if (value.k === "element") return this.hoist(value.index);
    if (value.k === "text") {
      return value.parts.flatMap((part) => (part.k === "value" ? this.hoist(part.value) : []));
    }
    return [];
  }

  private declarationOf(statement: ResolvedStatement & { kind: "declare" }): string {
    const value = statement.value;
    if (value.k === "buffer") {
      return `  const ${statement.name}_length = ${value.binding.length}.csize_t`;
    }
    if (value.k === "reference" && value.binding.kind === "buffer") {
      return [`  var ${statement.name} = ${value.name}`, `  const ${statement.name}_length = ${value.name}_length`].join(
        "\n",
      );
    }
    if (value.k === "text") {
      const text = value.parts
        .filter((part) => part.k === "text")
        .map((part) => part.value)
        .join("");
      return `  const ${statement.name} = ${nimString(text)}`;
    }
    const type = typeOfValue(value);
    if (type === null) throw hostError(`the driver cannot declare "${statement.name}"`);
    return `  var ${statement.name} = ${this.expression(value)}`;
  }

  /** The Nim statements that write one printed value. */
  private print(value: ResolvedValue): string[] {
    if (value.k === "text") {
      const body: string[] = [];
      let literalText = "";
      for (const part of value.parts) {
        if (part.k === "text") {
          literalText += part.value;
          continue;
        }
        if (literalText !== "") {
          body.push(`  stdout.write(${nimString(literalText)})`);
          literalText = "";
        }
        body.push(...this.print(part.value));
      }
      if (literalText !== "") body.push(`  stdout.write(${nimString(literalText)})`);
      return body;
    }
    if (value.k === "reference" && value.binding.kind === "string") {
      return [`  stdout.write(${value.name})`];
    }
    const scalar: ResolvedValue =
      value.k === "reference" && value.binding.kind === "scalar"
        ? { k: "literal", binding: { kind: "scalar", type: value.binding.type, text: value.name } }
        : value;
    const type = typeOfValue(scalar);
    if (type === null || type.kind !== "primitive") throw hostError("a program prints numbers and strings");
    if (isFloat(type)) return [`  stdout.write(programNumber(${this.expression(scalar)}))`];
    if (type.name === "bool") return [`  stdout.write(if ${this.expression(scalar)}: "true" else: "false")`];
    return [`  stdout.write($(${this.expression(scalar)}))`];
  }

  /** The Nim expression for a value, in the type its use asks for. */
  private expression(value: ResolvedValue, target: TypeExpr | null = null): string {
    const source = typeOfValue(value);
    const expression = this.raw(value);
    if (target === null || source === null || source.kind !== "primitive" || target.kind !== "primitive") {
      return expression;
    }
    if (source.name === target.name) return expression;
    return `${elementNim(target)}(${expression})`;
  }

  private raw(value: ResolvedValue): string {
    const buffer = this.bufferName(value);
    if (buffer !== null) return buffer;
    switch (value.k) {
      case "literal":
        return literal(value.binding.text, value.binding.type ?? "f64");
      case "length":
        return `${value.buffer}_length`;
      case "element":
        return `${value.buffer}[${this.expression(value.index, parseType("usize"))}]`;
      case "call":
        return this.callExpression(value.call);
      case "reference":
        if (value.binding.kind === "scalar" || value.binding.kind === "string") return value.name;
        throw hostError("the driver cannot write this value down");
      case "text":
        throw hostError("a string is not a value of a contracted function");
    }
    throw hostError("the driver cannot write this value down");
  }

  private bufferName(value: ResolvedValue): string | null {
    if (value.k === "buffer") return this.temporaries.get(value.binding) ?? null;
    if (value.k === "reference" && value.binding.kind === "buffer") return value.name;
    return null;
  }

  /** The call of a value, with every argument in the type its parameter takes. */
  private callExpression(call: ResolvedCall): string {
    const argumentsList = call.args.map(
      (argument, index) => this.argument(argument, parseType(call.signature.params[index].type)),
    );
    return `${call.name}(${argumentsList.join(", ")})`;
  }

  private argument(value: ResolvedValue, target: TypeExpr): string {
    if (target.kind === "ptr" || target.kind === "slice" || target.kind === "array") {
      const buffer = this.bufferName(value);
      if (buffer === null) throw hostError(`a ${typeToString(target)} parameter takes a buffer`);
      return `cast[ptr ${elementNim(target.of)}](${buffer})`;
    }
    if (target.kind !== "primitive") throw hostError(`a program cannot pass ${typeToString(target)}`);
    return this.expression(value, target);
  }
}

/** Emits the Nim driver for a program. The driver is compiler code. */
export function generateProgramHostSource(program: ResolvedProgram): string {
  return new NimDriver(program).emit();
}

export interface ProgramHostRequest {
  program: ResolvedProgram;
  /** Directory the adapter, driver and executable are written to. */
  workDirectory: string;
  /** Object of every function of the program, in the order they compile. */
  objectPaths: string[];
  outputPath: string;
}

/** Compiles the adapter and the driver, and links the program objects in. */
export async function buildProgramHost(request: ProgramHostRequest): Promise<Runner> {
  const adapterPath = `${request.workDirectory}/${RUNTIME_NAME}.nim`;
  const hostPath = `${request.workDirectory}/program_host.nim`;
  await writeFile(adapterPath, generateRuntimeAdapterSource(), "utf8");
  await writeFile(hostPath, generateProgramHostSource(request.program), "utf8");

  const result = run(
    "nim",
    [
      "c",
      "--hints:off",
      "--warnings:off",
      "-d:release",
      `--nimcache:${request.workDirectory}/nimcache`,
      `--out:${request.outputPath}`,
      ...request.objectPaths.map((path) => `--passL:${path}`),
      hostPath,
    ],
    { timeoutMs: 600_000 },
  );
  if (result.spawnError !== undefined) {
    throw new CompilerError({
      category: "TargetError",
      stage: "host",
      message: "the Nim compiler is not available",
      detail: `${result.spawnError}\ninstall Nim, or build this project with --runtime none`,
    });
  }
  if (result.code !== 0) {
    throw hostError("the Nim program driver did not build", `${adapterPath}\n${hostPath}\n${result.stderr.trim()}`);
  }
  return { command: request.outputPath, args: [] };
}
