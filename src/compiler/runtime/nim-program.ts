const HOST_PRELUDE = `## Generated by the blaze compiler from a program. Do not edit.
import std/[strutils, math, os]
import ${RUNTIME_NAME}
## The arguments the program is given, as the numbers the source reads them
## as. The source reads an argument the way the language reads a string as a
## number: the spaces around it are not part of it, a base written before the
## digits is read in that base, and an argument that is not a number at all is
## NaN rather than a zero the source never wrote.
proc programNumber(text: string): float64 =
  let trimmed = text.strip()
  if trimmed.len == 0: return 0.0

  ## A base written before the digits is read in that base, one digit at a
  ## time, rather than left to what parseFloat makes of it: 0b101 is five,
  ## 0o17 is fifteen, and a prefix with no digits behind it is not a number.
  ## A base is never written behind a sign, so the base is looked for before
  ## one is taken off, and a signed argument that is based is not a number.
  var base = 0
  if trimmed.len > 2 and trimmed[0] == '0':
    if trimmed[1] in {'x', 'X'}: base = 16
    elif trimmed[1] in {'o', 'O'}: base = 8
    elif trimmed[1] in {'b', 'B'}: base = 2
  if base != 0:
    var value = 0.0
    for letter in trimmed[2 .. ^1]:
      let place = if letter in {'0'..'9'}: ord(letter) - ord('0')
                 elif letter in {'a'..'z'}: ord(letter) - ord('a') + 10
                 elif letter in {'A'..'Z'}: ord(letter) - ord('A') + 10
                 else: -1
      if place < 0 or place >= base: return blazeNaN()
      value = value * float64(base) + float64(place)
    return value

  ## What is left is a decimal, which is the one form a sign is written in
  ## front of, and the one word a decimal may spell.
  var negative = false
  var rest = trimmed
  if rest[0] == '+' or rest[0] == '-':
    negative = rest[0] == '-'
    rest = rest[1 .. ^1]
  if rest.len == 0: return blazeNaN()
  if rest == "Infinity": return (if negative: -Inf else: Inf)

  ## parseFloat also reads inf, nan and a base before the digits, none of which
  ## the language reads as a number, so an argument it would answer that the
  ## source would not is NaN rather than handed to it.
  if rest[0] != '.' and rest[0] notin {'0'..'9'}: return blazeNaN()
  if rest[0] == '0' and rest.len > 1 and rest[1] in {'x', 'X', 'o', 'O', 'b', 'B'}: return blazeNaN()
  ## A decimal holds a digit before its exponent and no underscore: the
  ## language reads 1_000, a lone dot and .e5 as not numbers, where parseFloat
  ## reads the first as a thousand and the other two as a zero.
  var mantissa = rest.len
  var exponentSeen = false
  for position, letter in rest:
    if letter == '_': return blazeNaN()
    if not exponentSeen and (letter == 'e' or letter == 'E'):
      mantissa = position
      exponentSeen = true
  var hasDigit = false
  for position in 0 ..< mantissa:
    if rest[position] in {'0'..'9'}: hasDigit = true
  if not hasDigit: return blazeNaN()

  try:
    let value = parseFloat(rest)
    return (if negative: -value else: value)
  except ValueError:
    return blazeNaN()

proc programNumbers(): seq[float64] =
  for index in 1 .. paramCount():
    result.add(programNumber(paramStr(index)))

proc programFail(message: string) =
  stderr.write("program: " & message & "\\n")
  quit(2)

## A number as the language writes it, which is what a string interpolates.
proc programText(value: float64): string =
  var text: array[64, char]
  discard ${RUNTIME_NAME}_format_number(value, cast[ptr uint8](addr text[0]), 64)
  $cast[cstring](addr text[0])

## The language carries a value that is not a number through max and min, and
## a tie between two zeros is answered by the sign: a maximum is +0 and a
## minimum is -0 however the two zeros were written, which is the one thing
## Nim's own max and min do not do.
proc programMax(left, right: float64): float64 =
  if left != left or right != right: left + right
  elif left > right: left
  elif right > left: right
  elif left == 0.0 and (classify(left) == fcNegZero or classify(right) == fcNegZero): 0.0
  else: left

proc programMin(left, right: float64): float64 =
  if left != left or right != right: left + right
  elif left < right: left
  elif right < left: right
  elif left == 0.0 and (classify(left) == fcNegZero or classify(right) == fcNegZero): -0.0
  else: left

## A half is rounded up, and a value that rounds to zero from below keeps its
## sign, which is what the source prints.
proc programRound(value: float64): float64 =
  let rounded = floor(value + 0.5)
  (if rounded == 0.0 and value < 0.0: -0.0 else: rounded)

## A number written at a fixed number of digits after the point, which is what
## x.toFixed(d) is: the same digits every time, rounded at the last of them,
## and never the exponent form the shortest writing falls back on. A negative
## count is no digits, which is the word the language rounds it to.
proc programFixed(value: float64, digits: int): string =
  ## A number that is not a number, and one of a million million million and
  ## over, is written as the language writes it rather than at the digits asked
  ## for: (1e21).toFixed(2) is 1e+21 and not the twenty two digits that follow
  ## the point.
  if value != value or classify(value) == fcInf or classify(value) == fcNegInf or abs(value) >= 1e21:
    programText(value)
  else:
    let written = formatFloat(value, ffDecimal, (if digits < 0: 0 else: digits))
    ## The sign of a zero is not written, and only a value that is one has none
    ## to write: -0.004 at two digits is -0.00 in the language as well.
    (if value == 0.0 and classify(value) == fcNegZero: written[1 .. ^1] else: written)

## The values a counted loop takes, in the order it takes them, as the source
## counts: the index is added to, as the source adds, because a multiplication
## would not give the same doubles, and the loop stops on the bound rather
## than on a count of its values, so writing the loop down costs nothing. An
## iterator is what keeps a continue working: resuming one runs the step.
iterator programValues[T: SomeNumber](first, last, stride: T, inclusive, down: bool): T =
  var value = first
  while (if down: (if inclusive: value >= last else: value > last)
         else: (if inclusive: value <= last else: value < last)):
    yield value
    (value += stride)

`;

function hostError(message: string, detail?: string): CompilerError {
  return new CompilerError({ category: "LinkError", stage: "host", message, detail });
}

const NIM_ELEMENT_SIZES: Record<string, number> = {
  bool: 1,
  i8: 1,
  i16: 2,
  i32: 4,
  i64: 8,
  u8: 1,
  u16: 2,
  u32: 4,
  u64: 8,
  f32: 4,
  f64: 8,
  usize: 8,
  isize: 8,
};

function elementNim(type: TypeExpr): string {
  if (type.kind !== "primitive") throw hostError(`the driver cannot hold a ${typeToString(type)} element`);
  return nimType(type);
}

/** The Nim type of one parameter: a reference is a pointer to a struct. */
function nimParameter(type: TypeExpr): string {
  if (type.kind === "ref") return type.name === undefined ? "pointer" : `ptr ${type.name}`;
  if (type.kind === "void") return "void";
  if (type.kind === "primitive") return elementNim(type);
  return `ptr ${elementNim(bufferElement(type))}`;
}

/** Nim holds a buffer as an unchecked array, so the driver can fill it. */
function bufferNimType(element: string): string {
  return `ptr UncheckedArray[${element}]`;
}

function elementSize(type: TypeExpr): number {
  const size = type.kind === "primitive" ? NIM_ELEMENT_SIZES[type.name] : undefined;
  if (size === undefined) throw hostError(`the driver cannot size a ${typeToString(type)} element`);
  return size;
}

function nimString(text: string): string {
  const escaped = text
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")
    .replace(/\r/g, "\\r");
  return `"${escaped}"`;
}

/** The Nim type an integer value is written as, its literal suffix and range. */
interface NimInteger {
  readonly type: string;
  readonly suffix: string;
  readonly low: bigint;
  readonly high: bigint;
}

const NIM_INTEGERS: Record<string, NimInteger> = {
  i8: { type: "int8", suffix: "'i8", low: -128n, high: 127n },
  i16: { type: "int16", suffix: "'i16", low: -32768n, high: 32767n },
  i32: { type: "int32", suffix: "'i32", low: -2147483648n, high: 2147483647n },
  i64: { type: "int64", suffix: "'i64", low: -9223372036854775808n, high: 9223372036854775807n },
  isize: { type: "clong", suffix: "'isize", low: -9223372036854775808n, high: 9223372036854775807n },
  u8: { type: "uint8", suffix: "'u8", low: 0n, high: 255n },
  u16: { type: "uint16", suffix: "'u16", low: 0n, high: 65535n },
  u32: { type: "uint32", suffix: "'u32", low: 0n, high: 4294967295n },
  u64: { type: "uint64", suffix: "'u64", low: 0n, high: 18446744073709551615n },
  usize: { type: "csize_t", suffix: ".csize_t", low: 0n, high: 18446744073709551615n },
};

/** The value of an integer literal, or null where the text is not one. */
function integerLiteral(text: string): bigint | null {
  if (/^[+-]?0[xX]/.test(text)) {
    // BigInt takes the sign of a decimal literal only.
    const negative = text.startsWith("-");
    return (negative ? -1n : 1n) * BigInt(negative ? text.slice(1) : text);
  }
  return /^[+-]?[0-9]+$/.test(text) ? BigInt(text) : null;
}

function literal(text: string, element: string): string {
  if (element === "bool") return text === "0" ? "false" : "true";
  if (element === "f32" || element === "f64") {
    // A value that is not a number has no decimal to write, and the source
    // writes it as a word. Nim spells the three of them its own way, and the
    // word the source used is an undeclared identifier there.
    if (text === "Infinity") return "Inf";
    if (text === "-Infinity") return "-Inf";
    if (text === "NaN") return "NaN";
    if (text === "-0") return "-0.0";
    if (/^[+-]?0[xX]/.test(text)) {
      // BigInt takes the sign of a decimal literal only.
      const negative = text.startsWith("-");
      const value = BigInt(negative ? text.slice(1) : text);
      return `${negative ? "-" : ""}${value.toString()}.0`;
    }
    return /^[+-]?[0-9]+$/.test(text) ? `${text}.0` : text;
  }
  const integer = NIM_INTEGERS[element];
  if (integer === undefined) return text;
  const value = integerLiteral(text);
  // Nim refuses a literal its type cannot hold, while the C driver writes one
  // and keeps the bits the cast leaves. A value the type holds is written as
  // the literal it is; one it does not is cast from its own bits in 64 bits.
  // The bits are the value, not its magnitude: `cast` reads them as they are,
  // so the magnitude of a negative value would leave the sign behind and a
  // `uint8` the source wrote as -1 came out as 1.
  if (value === null || (value >= integer.low && value <= integer.high)) return `${text}${integer.suffix}`;
  const bits = value < 0n ? (1n << 64n) + value : value;
  return `cast[${integer.type}](${bits}'u64)`;
}

/** The operator Nim spells for the one the source used: `&` concatenates. */
const NIM_OPERATORS: Record<string, string> = {
  "+": "+",
  "-": "-",
  "*": "*",
  "/": "/",
  "<<": "shl",
  ">>": "shr",
  ">>>": "ushr",
  "&": "and",
  "|": "or",
  "^": "xor",
  "<": "<",
  "<=": "<=",
  ">": ">",
  ">=": ">=",
};

/** A contract type, which is what an array holds and a loop counts in. */
function contractType(type: SemanticType): TypeExpr {
  if (isTextType(type)) throw hostError("the driver cannot write a string down as a contract type");
  return type;
}


/** The Nim driver of one program: how the host language spells the walk. */
class NimDriver implements ProgramTarget {
  private counter = 0;

  /** A name no other part of the program is holding. */
  private fresh(prefix: string): string {
    this.counter += 1;
    return `${prefix}_${this.counter}`;
  }

  prelude(program: SemanticProgram): string {
    const externs = program.functions.map((signature) => this.declaration(signature)).join("\n");
    const anchor = RUNTIME_ANCHOR.map((symbol) => `  cast[pointer](${symbol}),`).join("\n");
    return `${HOST_PRELUDE}

{.emit: """
${externs}
""".}

${nimObjectDeclarations(program.objects)}

${program.functions.map((signature) => this.importc(signature)).join("\n\n")}

proc main() =
  # Every entry point is named here, so the linker keeps the ones a candidate
  # calls even when this program does not call them itself.
  let runtimeAbi = [
${anchor}
  ]
  discard runtimeAbi.len
  ${RUNTIME_NAME}_initialize()
  let programArguments = programNumbers()
  if programArguments.len > 0:
    var argumentStorage = programArguments
    ${RUNTIME_NAME}_arguments_set(cast[ptr UncheckedArray[float64]](addr argumentStorage[0]), csize_t(argumentStorage.len))
  else:
    ${RUNTIME_NAME}_arguments_set(nil, 0)`;
  }

  openFunction(signature: FunctionSignature, parameters: { name: string; type: string }[]): string[] {
    // A function the program declares is a proc of its own: it is called by
    // name from the body that runs and from the other functions.
    const returns = nimParameter(parseType(signature.returns));
    const given = parameters
      .map((param) => `${param.name}: ${nimParameter(parseType(param.type))}`)
      .join(", ");
    return [`proc ${nimName(signature.symbol)}(${given}): ${returns} =`];
  }

  closeFunction(releases: readonly string[], returned: boolean): string[] {
    // What the body allocated is freed before it returns, in the reverse of the
    // order the body took it. A body that returns a value has already written
    // its `return`, and one that falls off the end returns nothing at all.
    return [...releases, ...(returned ? [] : ["return"]), ""];
  }

  returnValue(value: string): string {
    return `return ${value}`;
  }

  returnNothing(): string {
    return "return";
  }

  openProgram(): string[] {
    return [];
  }

  closeProgram(releases: readonly string[]): string[] {
    return [...releases, `${RUNTIME_NAME}_finalize()`];
  }

  epilogue(): string[] {
    return ["", "main()"];
  }

  /** The C prototype a candidate is linked against, emitted into the program. */
  private declaration(signature: FunctionSignature): string {
    const returns = parseType(signature.returns);
    if (returns.kind === "ptr" || returns.kind === "slice" || returns.kind === "array") {
      throw hostError(
        `a program cannot call ${signature.name}`,
        `${typeToString(returns)} is returned, and a program holds numbers and strings`,
      );
    }
    const parameters = signature.params.map((param) => `${cDeclarationType(parseType(param.type))} ${param.name}`);
    return `extern ${cDeclarationType(returns)} ${cSymbolName(signature.symbol)}(${parameters.join(", ") || "void"})${cSymbolLabel(signature.symbol)};`;
  }

  private importc(signature: FunctionSignature): string {
    const parameters = signature.params.map((param) => `${param.name}: ${nimParameter(parseType(param.type))}`);
    const returns = parseType(signature.returns);
    const result = returns.kind === "void" ? "" : `: ${nimType(returns)}`;
    return `proc ${signature.symbol}(${parameters.join(", ")})${result} {.importc: "${signature.symbol}", nodecl.}`;
  }

  type(type: SemanticType): string {
    return isTextType(type) ? "string" : nimParameter(type);
  }

  cast(type: SemanticType, expression: string): string {
    return `${isTextType(type) ? "string" : nimParameter(type)}(${expression})`;
  }

  asLength(expression: string, type: SemanticType): string {
    // A NaN is no count and is zero, which is what the language reads a length
    // that is not a number as. Nim's own conversion answers the largest size
    // there is for a NaN, and an allocation of that ends the run. The count is
    // bound because it is read twice and a value the IR calls is a call, and
    // the conversion is at the width the IR reads the value at rather than at
    // the width of a count.
    return `block:
  let program_count = ${expression}
  if program_count != program_count: ${literal("0", typeText(type))} else: ${isTextType(type) ? "string" : nimParameter(type)}(program_count)`;
  }

  literal(text: string, type: string): string {
    return literal(text, type);
  }

  declare(name: string, _type: SemanticType | null, value: string): string {
    return `var ${name} = ${value}`;
  }

  allocate(name: string, element: SemanticType, length: number, values: string[]): string[] {
    const written = elementNim(contractType(element));
    const bytes = length === 0 ? 1 : length;
    return [
      `const ${name}_length = ${length}.csize_t`,
      `var ${name} = cast[${bufferNimType(written)}](${RUNTIME_NAME}_allocate(${bytes} * ${elementSize(contractType(element))}))`,
      ...values.map((text, index) => `${name}[${index}] = ${text}`),
    ];
  }

  sized(name: string, element: SemanticType, count: string): string[] {
    // A block of a count the program settled on when it ran. The count is read
    // as a length and the block is cleared, so a read of an element the program
    // never wrote is the zero the language answers it with; a block of no
    // elements is one byte, because an allocation of nothing fails and the
    // language answers an empty array with an array.
    const written = elementNim(contractType(element));
    return [
      `const ${name}_length = (${count}).csize_t`,
      `var ${name} = cast[${bufferNimType(written)}](${RUNTIME_NAME}_allocate((if ${name}_length == 0'u64: 1'u64 else: ${name}_length).csize_t * ${elementSize(contractType(element))}))`,
    ];
  }

  view(name: string, element: SemanticType, base: string, offset: string, count: string): string[] {
    // A window of a block the program laid out: the same bytes read as the
    // element of the view, from the byte offset the view starts at. The block
    // is not freed here: it belongs to the name the program gave it, which was
    // declared before this one, and what a block frees is freed after every
    // window taken of it.
    const written = elementNim(contractType(element));
    return [
      `const ${name}_length = (${count}).csize_t`,
      `var ${name} = cast[${bufferNimType(written)}](cast[pointer](cast[uint8](${base}) + (${offset}).csize_t))`,
    ];
  }

  fill(name: string, index: string, element: SemanticType, value: string): string[] {
    const written = elementNim(contractType(element));
    return [`for ${index} in 0 ..< ${name}_length.csize_t: ${name}[${index}] = (${written})(${value})`];
  }

  alias(name: string, _element: SemanticType, source: string, length: string): string[] {
    return [`const ${name}_length = ${length}`, `var ${name} = ${source}`];
  }

  element(buffer: string, index: string): string {
    return `${buffer}[${index}]`;
  }

  assign(name: string, operator: string, value: string, type: SemanticType | null): string {
    // A string grows rather than adds, and Nim has no `+=` for one.
    if ((type === null || isTextType(type)) && operator === "+=") return `${name} = ${name} & (${value})`;
    return `${name} ${operator} ${value}`;
  }

  elementAssign(buffer: string, index: string, operator: string, value: string): string {
    return `${buffer}[${index}] ${operator} ${value}`;
  }

  update(name: string, operator: string, _prefix: boolean): string {
    return operator === "++" ? `inc ${name}` : `dec ${name}`;
  }

  release(name: string): string {
    return `${RUNTIME_NAME}_release(cast[pointer](${name}))`;
  }

  condition(expression: string, kind: ValueKind, type: SemanticType | null): string {
    if (kind === "text") return `(${expression}).len != 0`;
    if (kind === "reference") return `(${expression}) != nil`;
    if (kind === "boolean") return `(${expression})`;
    // A value that is not a number holds nothing, and `NaN != 0` is true here as
    // it is in C, so the test asks for a number that is a number.
    if (isFloat(type)) return `((${expression}) == (${expression}) and (${expression}) != 0.0)`;
    return `(${expression}) != 0`;
  }

  openBlock(): string {
    // A block only scopes names, and every name the driver declares is its own,
    // so the block is written as a branch that always holds: a `break` inside a
    // Nim `block:` leaves the block, and the source means the loop around it.
    return "if true:";
  }

  closeBody(): null {
    return null;
  }

  emptyBody(): string {
    return "discard";
  }

  openIf(condition: string): string {
    return `if ${condition}:`;
  }

  openElse(): string {
    return "else:";
  }

  openWhile(condition: string): string {
    return `while ${condition}:`;
  }

  openDo(condition: string): string[] {
    // Nim has no do-while. The loop runs while it has not run yet or its
    // condition holds, and the condition is tested at the top of every
    // iteration, so a `continue` inside the body reaches it.
    const name = this.fresh("do");
    return [`var ${name} = true`, `while ${name} or (${condition}):`, `  ${name} = false`];
  }

  closeDo(): string[] {
    return [];
  }

  openFor(
    variable: string,
    type: SemanticType,
    from: string,
    to: string,
    inclusive: boolean,
    down: boolean,
    step: string | null,
  ): string[] {
    if (step !== null) {
      // countup and countdown both want the size of the step and reach past
      // the bound they are given, which is wrong in two ways at once: a
      // descending step is negative, so Positive refuses it, and an exclusive
      // bound has to be moved a whole step to say so, which wraps in an
      // unsigned index and leaves the loop running until the index comes back
      // round. The iterator tests the bound itself, so the bound is the one the
      // source wrote and the step keeps the sign it was written with.
      return [
        `for ${variable} in programValues((${from}), (${to}), (${step}), ${inclusive ? "true" : "false"}, ${down ? "true" : "false"}):`,
      ];
    }
    if (!isNumber(type) || isFloat(type)) {
      // A loop that moves in fractions has no whole step to count in, so it
      // walks the values its index takes, in the order it takes them.
      return [
        `for ${variable} in programValues((${from}), (${to}), 1, ${inclusive ? "true" : "false"}, ${down ? "true" : "false"}):`,
      ];
    }
    if (down) {
      return [`for ${variable} in countdown((${from}), (${to}) ${inclusive ? "" : "+ 1"}):`];
    }
    return [`for ${variable} in (${from}) ..${inclusive ? "" : "<"} (${to}):`];
  }

  openForOf(index: string, variable: string, _type: SemanticType, buffer: string, length: string): string[] {
    return [
      `for ${index} in 0 ..< int(${length}):`,
      `  let ${variable} = ${buffer}[${index}]`,
    ];
  }

  /**
   * Nothing: the Nim host runs a parallel loop's turns in order.
   *
   * Nim spells a parallel loop `par for`, which needs the program compiled with
   * `--threads:on` and turns every allocation in it into one a lock guards. The
   * mark a loop carries says its turns do not depend on each other, so running
   * them in order is the same program, and that is what a host without threads
   * owes it.
   */
  parallelDirective(reductions: readonly SemanticReduction[]): [] {
    void reductions;
    return [];
  }

  breakLine(): string {
    return "break";
  }

  continueLine(): string {
    return "continue";
  }

  conditional(condition: string, then: string, otherwise: string): string {
    return `(if ${condition}: ${then} else: ${otherwise})`;
  }

  discard(expression: string, returnsNothing: boolean): string {
    return returnsNothing ? expression : `discard ${expression}`;
  }

  print(value: string, type: SemanticType | null, kind: ValueKind): string[] {
    if (kind === "text") return [`stdout.write(${value})`];
    if (kind === "null") return [`stdout.write("null")`];
    if (kind === "boolean") return [`stdout.write(if ${value}: "true" else: "false")`];
    if (type !== null && isFloat(type)) return [`${RUNTIME_NAME}_print_number(${value})`];
    return [`stdout.write($(${value}))`];
  }

  newline(): string {
    return `stdout.write("\\n")`;
  }

  call(call: SemanticCall, argumentsText: string[]): string {
    return `${call.signature.symbol}(${argumentsText.join(", ")})`;
  }

  builtin(call: SemanticCall, argumentsText: string[]): string {
    const argument = (index: number): string => argumentsText[index] ?? "0.0";
    switch (call.callee) {
      case "Math.abs":
        return `abs(${argument(0)})`;
      case "Math.sqrt":
        return `sqrt(${argument(0)})`;
      case "Math.floor":
        return `floor(${argument(0)})`;
      case "Math.round":
        return `programRound(${argument(0)})`;
      case "Math.trunc":
        return `trunc(${argument(0)})`;
      case "sharedBlock":
        return `cast[pointer](${RUNTIME_NAME}_allocate((${argument(0)}).csize_t))`;
      default:
        throw hostError(`the driver cannot write down ${call.callee}`);
    }
  }

  argument(type: SemanticType, expression: string): string {
    if (type.kind === "ptr" || type.kind === "slice" || type.kind === "array") {
      return `cast[ptr ${elementNim(bufferElement(type))}](${expression})`;
    }
    return expression;
  }

  argvCount(): string {
    return `${RUNTIME_NAME}_argv_count().csize_t`;
  }

  argv(index: string): string {
    return `${RUNTIME_NAME}_argv(csize_t(${index}))`;
  }

  min(left: string, right: string): string {
    return `programMin(${left}, ${right})`;
  }

  max(left: string, right: string): string {
    return `programMax(${left}, ${right})`;
  }

  stringLiteral(text: string): string {
    return nimString(text);
  }

  stringConcat(left: string, right: string): string {
    return `(${left}) & (${right})`;
  }

  stringLength(value: string): string {
    return `(${value}).len`;
  }

  stringEqual(left: string, right: string): string {
    return `(${left}) == (${right})`;
  }

  stringCompare(left: string, right: string): string {
    // `cmp` is the order two strings read in: negative, zero or positive. Two
    // strings in Nim are compared as text, so `<` would do, and `cmp` is the
    // one that says which of the three answers is which.
    return `cmp(${left}, ${right})`;
  }

  toText(value: string, type: SemanticType, digits: number | null): string {
    // Nothing prints as the word for it, as the language does: `$(nil)` is the
    // empty string, which the source never printed.
    if (type.kind === "void" || (type.kind === "ref" && type.of === null)) return '"null"';
    if (isBoolean(type)) return `(if ${value}: "true" else: "false")`;
    // A number written at a fixed number of digits is written at them whatever
    // it is, and not at the digits the shortest writing would choose.
    if (digits !== null) return `programFixed((${value}).float64, ${digits})`;
    return isFloat(type) ? `programText(${value})` : `$((${value}))`;
  }

  retain(value: string): string {
    return `discard ${RUNTIME_NAME}_retain(cast[pointer](${value}))`;
  }

  field(object: string, layout: string, field: string): string {
    // A reference is held as a pointer, and a pointer has no fields, so the
    // layout the access names is what the field is read through.
    return `(cast[${layout}](${object})).${field}`;
  }

  assignField(object: string, layout: string, field: string, value: string): string {
    return `(cast[${layout}](${object})).${field} = ${value}`;
  }

  buildObject(layout: string, fields: { field: string; value: string }[]): string {
    // An object is one value the program holds, so it is allocated and filled
    // where it is written: a block expression is how Nim spells several
    // statements as one value.
    const name = this.fresh("blaze_object");
    const written = fields.map((one) => `(cast[${layout}](${name})).${one.field} = ${one.value}`);
    return `(block: let ${name} = create(${RUNTIME_NAME}_object_new(sizeof(${layout}), alignof(${layout}))); ${written.join("; ")}; ${name})`;
  }

  raise(message: string): string {
    return `${RUNTIME_NAME}_raise(${message})`;
  }

  isNull(value: string, negate: boolean): string {
    return `((${value}) ${negate ? "!=" : "=="} nil)`;
  }

  nullLiteral(): string {
    return "nil";
  }

  modulo(left: string, right: string): string {
    return `((${left}) - ((${left}) div (${right})) * (${right}))`;
  }

  power(left: string, right: string): string {
    return `((${left}) ^ (${right}))`;
  }

  bitwiseNot(value: string): string {
    return `not (${value})`;
  }

  logicalNot(value: string): string {
    return `not (${value})`;
  }

  operator(op: string): string {
    const written = NIM_OPERATORS[op];
    if (written === undefined) throw hostError(`the driver cannot write ${op} down`);
    return written;
  }

  escape(name: string): string {
    return nimName(name);
  }
}

/** Emits the Nim driver for a program. The driver is compiler code. */
export function generateProgramHostSource(program: SemanticProgram): string {
  return generateProgramSource(program, new NimDriver());
}

export interface ProgramHostRequest {
  program: SemanticProgram;
  /** Directory the adapter, driver and executable are written to. */
  workDirectory: string;
  /** Object of every function of the program, in the order they compile. */
  objectPaths: string[];
  outputPath: string;
  /** How hard the build goes, which is what the driver is compiled at. */
  mode: BuildMode;
}

/** Compiles the adapter and the driver, and links the program objects in. */
export async function buildProgramHost(request: ProgramHostRequest): Promise<Runner> {
  const adapterPath = `${request.workDirectory}/${RUNTIME_NAME}.nim`;
  const hostPath = `${request.workDirectory}/program_host.nim`;
  await writeFile(adapterPath, generateRuntimeAdapterSource(request.mode), "utf8");
  await writeFile(hostPath, generateProgramHostSource(request.program), "utf8");

  const result = run(
    "nim",
    [
      "c",
      "--hints:off",
      "--warnings:off",
      ...nimOptimizationOptions(request.mode),
      `--nimcache:${request.workDirectory}/nimcache`,
      `--out:${request.outputPath}`,
      ...request.objectPaths.map((path) => `--passL:${path}`),
      hostPath,
    ],
    { timeoutMs: 600_000 },
  );
  if (result.spawnError !== undefined) {
    throw new CompilerError({
      category: "TargetError",
      stage: "host",
      message: "the Nim compiler is not available",
      detail: `${result.spawnError}\ninstall Nim, or build this project with --runtime none`,
    });
  }
  if (result.code !== 0) {
    throw hostError("the Nim program driver did not build", `${adapterPath}\n${hostPath}\n${result.stderr.trim()}`);
  }
  return { command: request.outputPath, args: [] };
}
