const HOST_PRELUDE = `## Generated by the blaze compiler from a program. Do not edit.
import std/[strutils, math, os]
import ${RUNTIME_NAME}
## The arguments the program is given, as the numbers the source reads them as.
proc programNumbers(): seq[float64] =
  for index in 1 .. paramCount():
    try:
      result.add(parseFloat(paramStr(index)))
    except ValueError:
      result.add(0.0)

proc programFail(message: string) =
  stderr.write("program: " & message & "\\n")
  quit(2)

## A number as the language writes it, which is what a string interpolates.
proc programText(value: float64): string =
  var text: array[64, char]
  discard ${RUNTIME_NAME}_format_number(value, cast[ptr uint8](addr text[0]), 64)
  $cast[cstring](addr text[0])

## The language carries a value that is not a number through max and min.
proc programMax(left, right: float64): float64 =
  (if left != left or right != right: left + right else: max(left, right))

proc programMin(left, right: float64): float64 =
  (if left != left or right != right: left + right else: min(left, right))

## A half is rounded up, and a value that rounds to zero from below keeps its
## sign, which is what the source prints.
proc programRound(value: float64): float64 =
  let rounded = floor(value + 0.5)
  (if rounded == 0.0 and value < 0.0: -0.0 else: rounded)

## The values a counted loop takes, in the order it takes them, as the source
## counts: the index is added to, as the source adds, because a multiplication
## would not give the same doubles, and the loop stops on the bound rather
## than on a count of its values, so writing the loop down costs nothing. An
## iterator is what keeps a continue working: resuming one runs the step.
iterator programValues[T: SomeNumber](first, last, stride: T, inclusive, down: bool): T =
  var value = first
  while (if down: (if inclusive: value >= last else: value > last)
         else: (if inclusive: value <= last else: value < last)):
    yield value
    (if down: value -= stride else: value += stride)

`;

function hostError(message: string, detail?: string): CompilerError {
  return new CompilerError({ category: "LinkError", stage: "host", message, detail });
}

const NIM_ELEMENT_SIZES: Record<string, number> = {
  bool: 1,
  i8: 1,
  i16: 2,
  i32: 4,
  i64: 8,
  u8: 1,
  u16: 2,
  u32: 4,
  u64: 8,
  f32: 4,
  f64: 8,
  usize: 8,
  isize: 8,
};

function elementNim(type: TypeExpr): string {
  if (type.kind !== "primitive") throw hostError(`the driver cannot hold a ${typeToString(type)} element`);
  return nimType(type);
}

/** The Nim type of one parameter: a reference is a pointer to a struct. */
function nimParameter(type: TypeExpr): string {
  if (type.kind === "ref") return type.name === undefined ? "pointer" : `ptr ${type.name}`;
  if (type.kind === "void") return "void";
  if (type.kind === "primitive") return elementNim(type);
  return `ptr ${elementNim(bufferElement(type))}`;
}

/** Nim holds a buffer as an unchecked array, so the driver can fill it. */
function bufferNimType(element: string): string {
  return `ptr UncheckedArray[${element}]`;
}

function elementSize(type: TypeExpr): number {
  const size = type.kind === "primitive" ? NIM_ELEMENT_SIZES[type.name] : undefined;
  if (size === undefined) throw hostError(`the driver cannot size a ${typeToString(type)} element`);
  return size;
}

function nimString(text: string): string {
  const escaped = text
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")
    .replace(/\r/g, "\\r");
  return `"${escaped}"`;
}

/** The Nim type an integer value is written as, its literal suffix and range. */
interface NimInteger {
  readonly type: string;
  readonly suffix: string;
  readonly low: bigint;
  readonly high: bigint;
}

const NIM_INTEGERS: Record<string, NimInteger> = {
  i8: { type: "int8", suffix: "'i8", low: -128n, high: 127n },
  i16: { type: "int16", suffix: "'i16", low: -32768n, high: 32767n },
  i32: { type: "int32", suffix: "'i32", low: -2147483648n, high: 2147483647n },
  i64: { type: "int64", suffix: "'i64", low: -9223372036854775808n, high: 9223372036854775807n },
  isize: { type: "clong", suffix: "'isize", low: -9223372036854775808n, high: 9223372036854775807n },
  u8: { type: "uint8", suffix: "'u8", low: 0n, high: 255n },
  u16: { type: "uint16", suffix: "'u16", low: 0n, high: 65535n },
  u32: { type: "uint32", suffix: "'u32", low: 0n, high: 4294967295n },
  u64: { type: "uint64", suffix: "'u64", low: 0n, high: 18446744073709551615n },
  usize: { type: "csize_t", suffix: ".csize_t", low: 0n, high: 18446744073709551615n },
};

/** The value of an integer literal, or null where the text is not one. */
function integerLiteral(text: string): bigint | null {
  if (/^[+-]?0[xX]/.test(text)) {
    // BigInt takes the sign of a decimal literal only.
    const negative = text.startsWith("-");
    return (negative ? -1n : 1n) * BigInt(negative ? text.slice(1) : text);
  }
  return /^[+-]?[0-9]+$/.test(text) ? BigInt(text) : null;
}

function literal(text: string, element: string): string {
  if (element === "bool") return text === "0" ? "false" : "true";
  if (element === "f32" || element === "f64") {
    if (/^[+-]?0[xX]/.test(text)) {
      // BigInt takes the sign of a decimal literal only.
      const negative = text.startsWith("-");
      const value = BigInt(negative ? text.slice(1) : text);
      return `${negative ? "-" : ""}${value.toString()}.0`;
    }
    return /^[+-]?[0-9]+$/.test(text) ? `${text}.0` : text;
  }
  const integer = NIM_INTEGERS[element];
  if (integer === undefined) return text;
  const value = integerLiteral(text);
  // Nim refuses a literal its type cannot hold, while the C driver writes one
  // and keeps the bits the cast leaves. A value the type holds is written as
  // the literal it is; one it does not is cast from the unsigned value it
  // wraps, so both drivers end up with the same number.
  if (value === null || (value >= integer.low && value <= integer.high)) return `${text}${integer.suffix}`;
  const wrapped = value < 0n ? `${-value}'u64` : `${value}'u64`;
  return `cast[${integer.type}](${wrapped})`;
}

/** The operator Nim spells for the one the source used: `&` concatenates. */
const NIM_OPERATORS: Record<string, string> = {
  "+": "+",
  "-": "-",
  "*": "*",
  "/": "/",
  "<<": "shl",
  ">>": "shr",
  "&": "and",
  "|": "or",
  "^": "xor",
  "<": "<",
  "<=": "<=",
  ">": ">",
  ">=": ">=",
};

function isFloat(type: TypeExpr | null): boolean {
  return type !== null && type.kind === "primitive" && (type.name === "f32" || type.name === "f64");
}

/** The Nim driver of one program: how the host language spells the walk. */
class NimDriver implements ProgramTarget {
  private counter = 0;

  /** A name no other part of the program is holding. */
  private fresh(prefix: string): string {
    this.counter += 1;
    return `${prefix}_${this.counter}`;
  }

  prelude(program: ResolvedProgram): string {
    const externs = program.functions.map((signature) => this.declaration(signature)).join("\n");
    const anchor = RUNTIME_ANCHOR.map((symbol) => `  cast[pointer](${symbol}),`).join("\n");
    return `${HOST_PRELUDE}

{.emit: """
${externs}
""".}

${nimObjectDeclarations(program.objects)}

${program.functions.map((signature) => this.importc(signature)).join("\n\n")}

proc main() =
  # Every entry point is named here, so the linker keeps the ones a candidate
  # calls even when this program does not call them itself.
  let runtimeAbi = [
${anchor}
  ]
  discard runtimeAbi.len
  ${RUNTIME_NAME}_initialize()
  let programArguments = programNumbers()
  if programArguments.len > 0:
    var argumentStorage = programArguments
    ${RUNTIME_NAME}_arguments_set(cast[ptr UncheckedArray[float64]](addr argumentStorage[0]), csize_t(argumentStorage.len))
  else:
    ${RUNTIME_NAME}_arguments_set(nil, 0)`;
  }

  openProgram(): string[] {
    return [];
  }

  closeProgram(releases: readonly string[]): string[] {
    return [...releases, `${RUNTIME_NAME}_finalize()`];
  }

  epilogue(): string[] {
    return ["", "main()"];
  }

  /** The C prototype a candidate is linked against, emitted into the program. */
  private declaration(signature: FunctionSignature): string {
    const returns = parseType(signature.returns);
    if (returns.kind === "ptr" || returns.kind === "slice" || returns.kind === "array") {
      throw hostError(
        `a program cannot call ${signature.name}`,
        `${typeToString(returns)} is returned, and a program holds numbers and strings`,
      );
    }
    const parameters = signature.params.map((param) => `${cDeclarationType(parseType(param.type))} ${param.name}`);
    return `extern ${cDeclarationType(returns)} ${signature.symbol}(${parameters.join(", ") || "void"});`;
  }

  private importc(signature: FunctionSignature): string {
    const parameters = signature.params.map((param) => `${param.name}: ${nimParameter(parseType(param.type))}`);
    const returns = parseType(signature.returns);
    const result = returns.kind === "void" ? "" : `: ${nimType(returns)}`;
    return `proc ${signature.symbol}(${parameters.join(", ")})${result} {.importc: "${signature.symbol}", nodecl.}`;
  }

  type(type: TypeExpr): string {
    return nimParameter(type);
  }

  cast(type: TypeExpr, expression: string): string {
    return `${nimParameter(type)}(${expression})`;
  }

  literal(text: string, type: string): string {
    return literal(text, type);
  }

  declare(name: string, _type: TypeExpr | null, value: string): string {
    return `var ${name} = ${value}`;
  }

  allocate(name: string, element: TypeExpr, length: number, values: string[]): string[] {
    const written = elementNim(element);
    const bytes = length === 0 ? 1 : length;
    return [
      `const ${name}_length = ${length}.csize_t`,
      `var ${name} = cast[${bufferNimType(written)}](${RUNTIME_NAME}_allocate(${bytes} * ${elementSize(element)}))`,
      ...values.map((text, index) => `${name}[${index}] = ${text}`),
    ];
  }

  alias(name: string, _element: TypeExpr, source: string, length: string): string[] {
    return [`const ${name}_length = ${length}`, `var ${name} = ${source}`];
  }

  element(buffer: string, index: string): string {
    return `${buffer}[${index}]`;
  }

  assign(name: string, operator: string, value: string, type: TypeExpr | null): string {
    // A string grows rather than adds, and Nim has no `+=` for one.
    if (type === null && operator === "+=") return `${name} = ${name} & (${value})`;
    return `${name} ${operator} ${value}`;
  }

  elementAssign(buffer: string, index: string, operator: string, value: string): string {
    return `${buffer}[${index}] ${operator} ${value}`;
  }

  update(name: string, operator: string, _prefix: boolean): string {
    return operator === "++" ? `inc ${name}` : `dec ${name}`;
  }

  release(name: string): string {
    return `${RUNTIME_NAME}_release(cast[pointer](${name}))`;
  }

  condition(expression: string, kind: ValueKind): string {
    if (kind === "text") return `(${expression}).len != 0`;
    if (kind === "reference") return `(${expression}) != nil`;
    if (kind === "boolean") return `(${expression})`;
    return `(${expression}) != 0`;
  }

  openBlock(): string {
    // A block only scopes names, and every name the driver declares is its own,
    // so the block is written as a branch that always holds: a `break` inside a
    // Nim `block:` leaves the block, and the source means the loop around it.
    return "if true:";
  }

  closeBody(): null {
    return null;
  }

  emptyBody(): string {
    return "discard";
  }

  openIf(condition: string): string {
    return `if ${condition}:`;
  }

  openElse(): string {
    return "else:";
  }

  openWhile(condition: string): string {
    return `while ${condition}:`;
  }

  openDo(condition: string): string[] {
    // Nim has no do-while. The loop runs while it has not run yet or its
    // condition holds, and the condition is tested at the top of every
    // iteration, so a `continue` inside the body reaches it.
    const name = this.fresh("do");
    return [`var ${name} = true`, `while ${name} or (${condition}):`, `  ${name} = false`];
  }

  closeDo(): string[] {
    return [];
  }

  openFor(
    variable: string,
    type: TypeExpr,
    from: string,
    to: string,
    inclusive: boolean,
    down: boolean,
    step: string | null,
  ): string[] {
    if (step !== null) {
      // countup and countdown both want the size of the step and reach past
      // the bound they are given, which is wrong in two ways at once: a
      // descending step is negative, so Positive refuses it, and an exclusive
      // bound has to be moved a whole step to say so, which wraps in an
      // unsigned index and leaves the loop running until the index comes back
      // round. The iterator tests the bound itself, so the bound is the one the
      // source wrote and the step keeps the sign it was written with.
      return [
        `for ${variable} in programValues((${from}), (${to}), (${step}), ${inclusive ? "true" : "false"}, ${down ? "true" : "false"}):`,
      ];
    }
    if (type.kind !== "primitive" || type.name === "f32" || type.name === "f64") {
      // A loop that moves in fractions has no whole step to count in, so it
      // walks the values its index takes, in the order it takes them.
      return [
        `for ${variable} in programValues((${from}), (${to}), 1, ${inclusive ? "true" : "false"}, ${down ? "true" : "false"}):`,
      ];
    }
    if (down) {
      return [`for ${variable} in countdown((${from}), (${to}) ${inclusive ? "" : "+ 1"}):`];
    }
    return [`for ${variable} in (${from}) ..${inclusive ? "" : "<"} (${to}):`];
  }

  openForOf(index: string, variable: string, _type: TypeExpr, buffer: string, length: string): string[] {
    return [
      `for ${index} in 0 ..< int(${length}):`,
      `  let ${variable} = ${buffer}[${index}]`,
    ];
  }

  breakLine(): string {
    return "break";
  }

  continueLine(): string {
    return "continue";
  }

  conditional(condition: string, then: string, otherwise: string): string {
    return `(if ${condition}: ${then} else: ${otherwise})`;
  }

  discard(expression: string, returnsNothing: boolean): string {
    return returnsNothing ? expression : `discard ${expression}`;
  }

  print(value: string, type: TypeExpr | null, kind: ValueKind): string[] {
    if (kind === "text") return [`stdout.write(${value})`];
    if (kind === "null") return [`stdout.write("null")`];
    if (kind === "boolean") return [`stdout.write(if ${value}: "true" else: "false")`];
    if (isFloat(type)) return [`${RUNTIME_NAME}_print_number(${value})`];
    return [`stdout.write($(${value}))`];
  }

  separator(): string {
    return `stdout.write(" ")`;
  }

  newline(): string {
    return `stdout.write("\\n")`;
  }

  call(call: ResolvedCall, argumentsText: string[]): string {
    return `${call.name}(${argumentsText.join(", ")})`;
  }

  builtin(call: ResolvedCall, argumentsText: string[]): string {
    const argument = (index: number): string => argumentsText[index] ?? "0.0";
    switch (call.name) {
      case "Math.max":
        return `programMax(${argument(0)}, ${argument(1)})`;
      case "Math.min":
        return `programMin(${argument(0)}, ${argument(1)})`;
      case "Math.abs":
        return `abs(${argument(0)})`;
      case "Math.floor":
        return `floor(${argument(0)})`;
      case "Math.round":
        return `programRound(${argument(0)})`;
      case "Math.trunc":
        return `trunc(${argument(0)})`;
      case ARGV_LENGTH:
        return `${RUNTIME_NAME}_argv_count().csize_t`;
      case ARGV:
        return `${RUNTIME_NAME}_argv(csize_t(${argument(0)}))`;
      default:
        throw hostError(`the driver cannot write down ${call.name}`);
    }
  }

  argument(type: TypeExpr, expression: string): string {
    if (type.kind === "ptr" || type.kind === "slice" || type.kind === "array") {
      return `cast[ptr ${elementNim(bufferElement(type))}](${expression})`;
    }
    return expression;
  }

  stringLiteral(text: string): string {
    return nimString(text);
  }

  stringConcat(left: string, right: string): string {
    return `(${left}) & (${right})`;
  }

  stringLength(value: string): string {
    return `(${value}).len`;
  }

  stringEqual(left: string, right: string): string {
    return `(${left}) == (${right})`;
  }

  numberText(value: string, type: TypeExpr | null): string {
    if (type !== null && type.kind === "primitive" && type.name === "bool") {
      return `(if ${value}: "true" else: "false")`;
    }
    return isFloat(type) ? `programText(${value})` : `$((${value}))`;
  }

  isNull(value: string, negate: boolean): string {
    return `((${value}) ${negate ? "!=" : "=="} nil)`;
  }

  nullLiteral(): string {
    return "nil";
  }

  modulo(left: string, right: string): string {
    return `((${left}) - ((${left}) div (${right})) * (${right}))`;
  }

  power(left: string, right: string): string {
    return `((${left}) ^ (${right}))`;
  }

  bitwiseNot(value: string): string {
    return `not (${value})`;
  }

  logicalNot(value: string): string {
    return `not (${value})`;
  }

  operator(op: string): string {
    const written = NIM_OPERATORS[op];
    if (written === undefined) throw hostError(`the driver cannot write ${op} down`);
    return written;
  }

  escape(name: string): string {
    return nimName(name);
  }
}

/** Emits the Nim driver for a program. The driver is compiler code. */
export function generateProgramHostSource(program: ResolvedProgram): string {
  return generateProgramSource(program, new NimDriver());
}

export interface ProgramHostRequest {
  program: ResolvedProgram;
  /** Directory the adapter, driver and executable are written to. */
  workDirectory: string;
  /** Object of every function of the program, in the order they compile. */
  objectPaths: string[];
  outputPath: string;
}

/** Compiles the adapter and the driver, and links the program objects in. */
export async function buildProgramHost(request: ProgramHostRequest): Promise<Runner> {
  const adapterPath = `${request.workDirectory}/${RUNTIME_NAME}.nim`;
  const hostPath = `${request.workDirectory}/program_host.nim`;
  await writeFile(adapterPath, generateRuntimeAdapterSource(), "utf8");
  await writeFile(hostPath, generateProgramHostSource(request.program), "utf8");

  const result = run(
    "nim",
    [
      "c",
      "--hints:off",
      "--warnings:off",
      "-d:release",
      `--nimcache:${request.workDirectory}/nimcache`,
      `--out:${request.outputPath}`,
      ...request.objectPaths.map((path) => `--passL:${path}`),
      hostPath,
    ],
    { timeoutMs: 600_000 },
  );
  if (result.spawnError !== undefined) {
    throw new CompilerError({
      category: "TargetError",
      stage: "host",
      message: "the Nim compiler is not available",
      detail: `${result.spawnError}\ninstall Nim, or build this project with --runtime none`,
    });
  }
  if (result.code !== 0) {
    throw hostError("the Nim program driver did not build", `${adapterPath}\n${hostPath}\n${result.stderr.trim()}`);
  }
  return { command: request.outputPath, args: [] };
}
